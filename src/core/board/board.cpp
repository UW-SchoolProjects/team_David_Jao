void clear_board(Board &b) {

    for (int i = 0; i < BOARD_SIZE; i++) {
        b.squares[i] = EMPTY;
    }
    b.side = WHITE;            
    b.castling = 0;            
    b.ep_square = NO_SQUARE;   
    b.halfmove_clock = 0;
    b.fullmove_number = 1;
    b.zobrist_key = 0ULL; 
    
    for (int i = 0; i < 16; i++) {
        b.bb_piece[i] = 0ULL;
    }
    b.bb_side[0] = 0ULL;
    b.bb_side[1] = 0ULL;
    b.bb_occ = 0ULL;
}

void setup_startpos(Board &b) {
    clear_board(b);
    for (int i = 0; i < 8; i++) {
        b.squares[0x10 + i] = WPAWN;
    }
    for (int i = 0; i < 8; i++) {
        b.squares[0x60 + i] = BPAWN;
    }
    b.squares[0x0] = WROOK;
    b.squares[0x1] = WKNIGHT;
    b.squares[0x2] = WBISHOP;
    b.squares[0x3] = WQUEEN;
    b.squares[0x4] = WKING;
    b.squares[0x5] = WBISHOP;
    b.squares[0x6] = WKNIGHT;
    b.squares[0x7] = WROOK;
    b.squares[0x70] = BROOK;
    b.squares[0x71] = BKNIGHT;
    b.squares[0x72] = BBISHOP;
    b.squares[0x73] = BQUEEN;
    b.squares[0x74] = BKING;
    b.squares[0x75] = BBISHOP;
    b.squares[0x76] = BKNIGHT;
    b.squares[0x77] = BROOK;

    b.castling = WKCA | WQCA | BKCA | BQCA;
    b.ep_square = NO_SQUARE;
    b.halfmove_clock = 0;
    b.fullmove_number = 1;
    b.side = WHITE;   
    b.zobrist_key = compute_zobrist(b);

    rebuild_bitboards(b);
}

void rebuild_bitboards(Board& b) {
    // Reset all bitboards
    for (int i = 0; i < 16; ++i) b.bb_piece[i] = 0ULL;
    b.bb_side[0] = b.bb_side[1] = 0ULL;
    b.bb_occ = 0ULL;

    // Add every non-empty piece
    for (int rank = 0; rank < 8; ++rank) {
        for (int file = 0; file < 8; ++file) {
            int sq0x88 = MAKE_SQUARE(file, rank);
            int piece = b.squares[sq0x88];
            if (piece != EMPTY) {
                int sq64 = BB_INDEX(file, rank);
                bb_set_piece(b, sq64, piece);
            }
        }
    }
}

bool assert_bb_consistency(const Board& b) {
    Board tmp = b;
    rebuild_bitboards(tmp);

    for (int i = 0; i < 16; ++i) {
        if (tmp.bb_piece[i] != b.bb_piece[i]) {
            std::cerr << "Bitboard mismatch: bb_piece[" << i << "]\n";
            return false;
        }
    }

    for (int c = 0; c < 2; ++c) {
        if (tmp.bb_side[c] != b.bb_side[c]) {
            std::cerr << "Bitboard mismatch: bb_side[" << c << "]\n";
            return false;
        }
    }

    if (tmp.bb_occ != b.bb_occ) {
        std::cerr << "Bitboard mismatch: bb_occ\n";
        return false;
    }

    return true;
}

static int piece_from_fen_char(char c) {
    switch (c) {
    case 'P': return WPAWN;
    case 'N': return WKNIGHT;
    case 'B': return WBISHOP;
    case 'R': return WROOK;
    case 'Q': return WQUEEN;
    case 'K': return WKING;
    case 'p': return BPAWN;
    case 'n': return BKNIGHT;
    case 'b': return BBISHOP;
    case 'r': return BROOK;
    case 'q': return BQUEEN;
    case 'k': return BKING;
    default:  return -1;
    }
}

bool load_fen(Board &b, const std::string &fen) {
    std::istringstream iss(fen);
    std::string placement, stm, castling, ep;
    int halfmove = 0;
    int fullmove = 1;

    if (!(iss >> placement >> stm >> castling >> ep >> halfmove >> fullmove)) {
        return false;
    }
    // Reject extra tokens beyond the six FEN fields.
    std::string extra;
    if (iss >> extra) {
        return false;
    }

    clear_board(b);

    int rank = 7;
    int file = 0;
    int seen_slashes = 0;
    for (size_t idx = 0; idx < placement.size(); ++idx) {
        char c = placement[idx];
        if (c == '/') {
            if (file != 8 || rank == 0) return false;
            --rank;
            ++seen_slashes;
            file = 0;
            continue;
        }
        if (std::isdigit(static_cast<unsigned char>(c))) {
            int n = c - '0';
            // Reject zero and any count that would overrun the rank.
            if (n <= 0 || file + n > 8) return false;
            file += n;
            continue;
        }

        int piece = piece_from_fen_char(c);
        if (piece == -1 || file >= 8 || rank < 0) return false;

        int sq = MAKE_SQUARE(file, rank);
        b.squares[sq] = piece;
        ++file;

        // Early guard: no rank may exceed 8 squares.
        if (file > 8) return false;
    }
    // Expect exactly 8 ranks (7 slashes) and complete final rank.
    if (rank != 0 || file != 8 || seen_slashes != 7) return false;

    // Validate side to move strictly.
    if (stm.size() != 1) return false;
    char stm_ch = stm[0];
    if (stm_ch == 'w')      b.side = WHITE;
    else if (stm_ch == 'b') b.side = BLACK;
    else return false;

    b.castling = 0;
    if (castling != "-") {
        for (char c : castling) {
            switch (c) {
            case 'K': b.castling |= WKCA; break;
            case 'Q': b.castling |= WQCA; break;
            case 'k': b.castling |= BKCA; break;
            case 'q': b.castling |= BQCA; break;
            default: return false;
            }
        }
    }

    b.ep_square = NO_SQUARE;
    if (ep != "-") {
        if (ep.size() != 2) return false;
        char fileChar = ep[0];
        char rankChar = ep[1];
        if (fileChar < 'a' || fileChar > 'h' || rankChar < '1' || rankChar > '8') return false;
        // EP square must be on the correct rank for the side to move.
        if ((b.side == WHITE && rankChar != '6') || (b.side == BLACK && rankChar != '3')) {
            return false;
        }
        int f = fileChar - 'a';
        int r = rankChar - '1';
        int ep_sq = MAKE_SQUARE(f, r);
        // EP target square must be empty.
        if (b.squares[ep_sq] != EMPTY) return false;
        b.ep_square = ep_sq;
    }

    if (halfmove < 0) halfmove = 0;
    if (fullmove < 1) fullmove = 1;
    b.halfmove_clock = halfmove;
    b.fullmove_number = fullmove;

    rebuild_bitboards(b);
    b.zobrist_key = compute_zobrist(b);
    return true;
}

std::string dump_fen(const Board &b) {
    std::ostringstream out;

    for (int rank = 7; rank >= 0; --rank) {
        int empty = 0;
        for (int file = 0; file < 8; ++file) {
            int sq = MAKE_SQUARE(file, rank);
            int piece = b.squares[sq];
            if (piece == EMPTY) {
                ++empty;
                continue;
            }
            if (empty > 0) {
                out << empty;
                empty = 0;
            }
            char c = '?';
            switch (piece) {
            case WPAWN:   c = 'P'; break;
            case WKNIGHT: c = 'N'; break;
            case WBISHOP: c = 'B'; break;
            case WROOK:   c = 'R'; break;
            case WQUEEN:  c = 'Q'; break;
            case WKING:   c = 'K'; break;
            case BPAWN:   c = 'p'; break;
            case BKNIGHT: c = 'n'; break;
            case BBISHOP: c = 'b'; break;
            case BROOK:   c = 'r'; break;
            case BQUEEN:  c = 'q'; break;
            case BKING:   c = 'k'; break;
            default:      c = '?'; break;
            }
            out << c;
        }
        if (empty > 0) out << empty;
        if (rank != 0) out << '/';
    }

    out << ' ' << (b.side == WHITE ? 'w' : 'b') << ' ';

    std::string castling;
    if (b.castling & WKCA) castling.push_back('K');
    if (b.castling & WQCA) castling.push_back('Q');
    if (b.castling & BKCA) castling.push_back('k');
    if (b.castling & BQCA) castling.push_back('q');
    out << (castling.empty() ? "-" : castling) << ' ';

    if (b.ep_square == NO_SQUARE) {
        out << "-";
    } else {
        int file = FILE_OF(b.ep_square);
        int rank = RANK_OF(b.ep_square);
        out << char('a' + file) << char('1' + rank);
    }

    out << ' ' << b.halfmove_clock << ' ' << b.fullmove_number;
    return out.str();
}

bool is_square_onboard(int sq) {
    return IS_ONBOARD(sq);
}

void print_board(const Board &b) {
    for (int i = 7; i >= 0; i--) {
        cout << i + 1 << " ";
        for (int j = 0; j < 8; j++) {
            auto piece = b.squares[MAKE_SQUARE(j, i)];

            if (piece == WPAWN) {
                cout << " wP"; 
            } else if (piece == WROOK) {
                cout << " wR"; 
            } else if (piece == WKNIGHT) {
                cout << " wN"; 
            } else if (piece == WBISHOP) {
                cout << " wB"; 
            } else if (piece == WQUEEN) {
                cout << " wQ"; 
            } else if (piece == WKING) {
                cout << " wK"; 
            } else if (piece == BPAWN) {
                cout << " bP"; 
            } else if (piece == BROOK) {
                cout << " bR"; 
            } else if (piece == BKNIGHT) {
                cout << " bN"; 
            } else if (piece == BBISHOP) {
                cout << " bB"; 
            } else if (piece == BQUEEN) {
                cout << " bQ"; 
            } else if (piece == BKING) {
                cout << " bK"; 
            } else {
                cout << " --";
            }
        }
        cout << endl;
    }
    cout << "    a  b  c  d  e  f  g  h" << endl;
}
