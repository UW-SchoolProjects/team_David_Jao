// ---------------------------------------------------------
// 1.2.3 — Pawns, Promotions & En Passant
// ---------------------------------------------------------
static void generatePawnMoves(const Board &board, Side side, MoveList &pseudoMoves)
{
  uint64_t myPawns = bb_of(board, side == WHITE ? WPAWN : BPAWN);
  if (!myPawns)
    return;

  // uint64_t myOcc = occ_side(board, side);
  uint64_t oppOcc = occ_side(board, 1 - side);
  uint64_t occAll = occ_all(board);

  // EP target as bit index, if any
  int epBit = -1;
  if (board.ep_square != NO_SQUARE)
  {
    epBit = square0x88ToBitIndex(board.ep_square);
  }

  //   auto appendMoves = [&](uint64_t targets, int from)
  auto getCaptures = [&](int to, int from, int prorank)
  {
    uint64_t mask = 1ULL << to;
    if (oppOcc & mask)
    {
      int toRank = to / 8;
      PieceType captured = getCapturedPieceType(board, to);
      if (toRank == prorank)
      {
        PieceType promos[4] = {QUEEN, ROOK, BISHOP, KNIGHT};
        for (PieceType pt : promos)
        {
          Move m(from, to, static_cast<MoveFlag>(MF_CAPTURE | MF_PROMOTION),
                 pt, captured);
          pseudoMoves.add(m);
        }
      }
      else
      {
        Move m(from, to, MF_CAPTURE, EMPTY, captured);
        pseudoMoves.add(m);
      }
    }
    // En passant capture
    if (epBit == to)
    {
      Move m(from, to, static_cast<MoveFlag>(MF_CAPTURE | MF_EN_PASSANT_CAPTURE),
             EMPTY, PAWN);
      pseudoMoves.add(m);
    }
  };

  while (myPawns)
  {
    int from = popLsb(myPawns);
    int rank = from / 8;
    int file = from % 8;

    if (side == WHITE)
    {
      // --- Single push ---
      int oneStep = from + 8;
      if (oneStep < 64 && !(occAll & (1ULL << oneStep)))
      {
        int toRank = oneStep / 8;

        if (toRank == 7)
        {
          // Promotion quiet (to rank 8)
          PieceType promos[4] = {QUEEN, ROOK, BISHOP, KNIGHT};
          for (PieceType pt : promos)
          {
            Move m(from, oneStep, MF_PROMOTION, pt, EMPTY);
            pseudoMoves.add(m);
          }
        }
        else
        {
          Move m(from, oneStep, MF_QUIET, EMPTY, EMPTY);
          pseudoMoves.add(m);

          // --- Double push from rank 2 (rank == 1) ---
          if (rank == 1)
          {
            int twoStep = from + 16;
            if (!(occAll & (1ULL << twoStep)))
            {
              Move dm(from, twoStep, MF_DOUBLE_PAWN_PUSH, EMPTY, EMPTY);
              pseudoMoves.add(dm);
            }
          }
        }
      }

      // --- Captures (including promo captures) ---
      // Left capture (from White's POV): +7 (file > 0)
      if (file > 0)
      {
        int to = from + 7;
        if (to < 64)
        {
          getCaptures(to, from, 7);
        }
      }

      // Right capture: +9 (file < 7)
      if (file < 7)
      {
        int to = from + 9;
        if (to < 64)
        {
          getCaptures(to, from, 7);
        }
      }
    }
    else
    {
      // side == BLACK
      // --- Single push ---
      int oneStep = from - 8;
      if (oneStep >= 0 && !(occAll & (1ULL << oneStep)))
      {
        int toRank = oneStep / 8;
        if (toRank == 0)
        {
          // Promotion quiet to rank 1
          PieceType promos[4] = {QUEEN, ROOK, BISHOP, KNIGHT};
          for (PieceType pt : promos)
          {
            Move m(from, oneStep, MF_PROMOTION, pt, EMPTY);
            pseudoMoves.add(m);
          }
        }
        else
        {
          Move m(from, oneStep, MF_QUIET, EMPTY, EMPTY);
          pseudoMoves.add(m);

          // Double push from rank 7 (rank == 6)
          if (rank == 6)
          {
            int twoStep = from - 16;
            if (!(occAll & (1ULL << twoStep)))
            {
              Move dm(from, twoStep, MF_DOUBLE_PAWN_PUSH, EMPTY, EMPTY);
              pseudoMoves.add(dm);
            }
          }
        }
      }

      // --- Captures ---
      // Left capture (from Black's POV): -9 (file > 0)
      if (file > 0)
      {
        int to = from - 9;
        if (to >= 0)
        {
          getCaptures(to, from, 0);
        }
      }

      // Right capture: -7 (file < 7)
      if (file < 7)
      {
        int to = from - 7;
        if (to >= 0)
        {
          getCaptures(to, from, 0);
        }
      }
    }
  }
}

/**
 * Generate pseudolegal moves (ignores self-check) for a side.
 * This is the "Parent Job 1.2" umbrella, which delegates to the
 * specific piece-type generators.
 */
static void generatePseudoLegalMoves(const Board &board,
                                     Side side,
                                     MoveList &pseudoMoves)
{
  pseudoMoves.clear();

  uint64_t myOcc = occ_side(board, side);
  uint64_t oppOcc = occ_side(board, 1 - side);
  uint64_t occ = occ_all(board);

  // "Inner function": lambda capturing board, myOcc, oppOcc and pseudoMoves
  auto appendMoves = [&](uint64_t targets, int from)
  {
    uint64_t quiets = targets & ~oppOcc;
    uint64_t captures = targets & oppOcc;

    uint64_t bb = quiets;
    while (bb)
    {
      int to = popLsb(bb);
      Move m(from, to, MF_QUIET, EMPTY, EMPTY);
      pseudoMoves.add(m);
    }

    bb = captures;
    while (bb)
    {
      int to = popLsb(bb);
      PieceType captured = getCapturedPieceType(board, to);
      Move m(from, to, MF_CAPTURE, EMPTY, captured);
      pseudoMoves.add(m);
    }
  };

  // Knight Moves
  uint64_t myKnights = bb_of(board, side == WHITE ? WKNIGHT : BKNIGHT);
  while (myKnights)
  {
    int from = popLsb(myKnights);
    uint64_t targets = knightAttacks[from] & ~myOcc;

    appendMoves(targets, from);
  }

  // King Moves
  uint64_t myKing = bb_of(board, side == WHITE ? WKING : BKING);
  if (myKing)
  {
    int from = __builtin_ctzll(myKing); // only one king
    uint64_t targets = kingAttacks[from] & ~myOcc;

    appendMoves(targets, from);

    // Castling will be added later (pseudolegal: check only empty & rights)
    // --- Castling (pseudolegal: rights + emptiness only) ---
    if (side == WHITE)
    {
      // White king must be on e1 (file=4, rank=0) to castle
      const int E1 = BB_INDEX(4, 0);
      const int F1 = BB_INDEX(5, 0);
      const int G1 = BB_INDEX(6, 0);
      const int D1 = BB_INDEX(3, 0);
      const int C1 = BB_INDEX(2, 0);
      const int B1 = BB_INDEX(1, 0);

      if (from == E1)
      {
        // Kingside castle: e1 -> g1, rights WKCA, squares f1 and g1 must be empty
        if (board.castling & WKCA)
        {
          uint64_t between = BIT(F1) | BIT(G1);
          if ((occ & between) == 0)
          {
            Move m(E1, G1, MF_KING_CASTLE, EMPTY, EMPTY);
            pseudoMoves.add(m);
          }
        }

        // Queenside castle: e1 -> c1, rights WQCA, squares d1, c1, b1 must be empty
        if (board.castling & WQCA)
        {
          uint64_t between = BIT(D1) | BIT(C1) | BIT(B1);
          if ((occ & between) == 0)
          {
            Move m(E1, C1, MF_QUEEN_CASTLE, EMPTY, EMPTY);
            pseudoMoves.add(m);
          }
        }
      }
    }
    else
    {
      // side == BLACK
      // Black king must be on e8 (file=4, rank=7) to castle
      const int E8 = BB_INDEX(4, 7);
      const int F8 = BB_INDEX(5, 7);
      const int G8 = BB_INDEX(6, 7);
      const int D8 = BB_INDEX(3, 7);
      const int C8 = BB_INDEX(2, 7);
      const int B8 = BB_INDEX(1, 7);

      if (from == E8)
      {
        // Kingside castle: e8 -> g8, rights BKCA, squares f8 and g8 empty
        if (board.castling & BKCA)
        {
          uint64_t between = BIT(F8) | BIT(G8);
          if ((occ & between) == 0)
          {
            Move m(E8, G8, MF_KING_CASTLE, EMPTY, EMPTY);
            pseudoMoves.add(m);
          }
        }

        // Queenside castle: e8 -> c8, rights BQCA, squares d8, c8, b8 empty
        if (board.castling & BQCA)
        {
          uint64_t between = BIT(D8) | BIT(C8) | BIT(B8);
          if ((occ & between) == 0)
          {
            Move m(E8, C8, MF_QUEEN_CASTLE, EMPTY, EMPTY);
            pseudoMoves.add(m);
          }
        }
      }
    }
  }

  // Bishop Moves
  uint64_t myBishops = bb_of(board, side == WHITE ? WBISHOP : BBISHOP);
  while (myBishops)
  {
    int from = popLsb(myBishops);
    uint64_t attacks = bishopAttacks(from, occ) & ~myOcc;

    appendMoves(attacks, from);
  }

  // Rook Moves
  uint64_t myRooks = bb_of(board, side == WHITE ? WROOK : BROOK);
  while (myRooks)
  {
    int from = popLsb(myRooks);
    uint64_t attacks = rookAttacks(from, occ) & ~myOcc;

    appendMoves(attacks, from);
  }

  // Queen Moves
  uint64_t myQueens = bb_of(board, side == WHITE ? WQUEEN : BQUEEN);
  while (myQueens)
  {
    int from = popLsb(myQueens);
    uint64_t attacks =
        (bishopAttacks(from, occ) |
         rookAttacks(from, occ)) &
        ~myOcc;

    appendMoves(attacks, from);
  }

  // Pawn Moves
  generatePawnMoves(board, side, pseudoMoves);
}

/**
 * Task 2.1.1 — Check detection.
 * Returns true if `side`'s king is currently in check.
 */
bool isInCheck(const Board &board, Side side)
{
  // 1. Locate our king (as a bitboard and as a 0..63 index)
  U64 myKing = bb_of(board, side == WHITE ? WKING : BKING);
  assert(myKing != 0);
  if (myKing == 0) {
    // Defensive fallback in non-assert builds to avoid UB.
    return false;
  }

  int kingSq = lsb_index(myKing); // 0..63 index
  int rank = kingSq / 8;
  int file = kingSq % 8;

  // 2. Basic occupancy and side setup
  Side opp = (side == WHITE ? BLACK : WHITE);
  U64 occAll = occ_all(board);

  // 3. Pawn attacks onto king square
  {
    U64 oppPawns = bb_of(board, (opp == WHITE ? WPAWN : BPAWN));

    // We work "backwards": from the king square, which squares
    // could contain an enemy pawn that attacks this square?

    if (opp == WHITE)
    {
      // White pawns move up (towards higher ranks) and capture +7 / +9.
      // So a white pawn that attacks kingSq must sit on kingSq-7 or kingSq-9.
      if (rank > 0)
      {
        if (file > 0)
        {
          int fromSq = kingSq - 9;
          if (fromSq >= 0 && (oppPawns & BIT(fromSq)))
            return true;
        }
        if (file < 7)
        {
          int fromSq = kingSq - 7;
          if (fromSq >= 0 && (oppPawns & BIT(fromSq)))
            return true;
        }
      }
    }
    else
    {
      // opp == BLACK
      // Black pawns move down (towards lower ranks) and capture -7 / -9.
      // So a black pawn that attacks kingSq must sit on kingSq+7 or kingSq+9.
      if (rank < 7)
      {
        if (file > 0)
        {
          int fromSq = kingSq + 7;
          if (fromSq < 64 && (oppPawns & BIT(fromSq)))
            return true;
        }
        if (file < 7)
        {
          int fromSq = kingSq + 9;
          if (fromSq < 64 && (oppPawns & BIT(fromSq)))
            return true;
        }
      }
    }
  }

  // 4. Knight attacks
  {
    U64 oppKnights = bb_of(board, (opp == WHITE ? WKNIGHT : BKNIGHT));
    if (knightAttacks[kingSq] & oppKnights)
      return true;
  }

  // 5. Diagonal sliders: bishops and queens
  {
    U64 oppBishopsQueens =
        bb_of(board, (opp == WHITE ? WBISHOP : BBISHOP)) |
        bb_of(board, (opp == WHITE ? WQUEEN : BQUEEN));

    if (oppBishopsQueens)
    {
      U64 attacks = bishopAttacks(kingSq, occAll);
      if (attacks & oppBishopsQueens)
        return true;
    }
  }

  // 6. Orthogonal sliders: rooks and queens
  {
    U64 oppRooksQueens =
        bb_of(board, (opp == WHITE ? WROOK : BROOK)) |
        bb_of(board, (opp == WHITE ? WQUEEN : BQUEEN));

    if (oppRooksQueens)
    {
      U64 attacks = rookAttacks(kingSq, occAll);
      if (attacks & oppRooksQueens)
        return true;
    }
  }

  // 7. Opponent king adjacency (illegal to have kings touching)
  {
    U64 oppKing = bb_of(board, (opp == WHITE ? WKING : BKING));
    if (kingAttacks[kingSq] & oppKing)
      return true;
  }

  // 8. No attackers found
  return false;
}

/**
 * Task 2.2 — Forced capture rule.
 * If at least one capture exists in `moves`,
 * remove all non-captures.
 */
static void applyCaptureOnlyFilter(MoveList &moves)
{
  // Nothing to do for empty list
  if (moves.count == 0)
    return;

  // 1) First pass: check if there is at least one capture
  bool hasCapture = false;
  for (int i = 0; i < moves.count; ++i)
  {
    if (moves.moves[i].isCapture())
    {
      hasCapture = true;
      break;
    }
  }

  // If no captures exist, we keep all moves (normal chess behavior)
  if (!hasCapture)
    return;

  // 2) Second pass: compact the list to only captures (in-place)
  int writeIdx = 0;
  for (int i = 0; i < moves.count; ++i)
  {
    if (moves.moves[i].isCapture())
    {
      moves.moves[writeIdx++] = moves.moves[i];
    }
  }

  // Update count to the number of captures kept
  moves.count = writeIdx;
}

static void validMoveGeneration_ApproachA(const Board &board,
                                          Side side,
                                          MoveList &outMoves)
{
  outMoves.clear();

  bool inCheck = isInCheck(board, side);

  // 1) Generate all pseudolegal moves (captures + quiets)
  generatePseudoLegalMoves(board, side, outMoves);

  // 2) Legalize IN-PLACE:
  int writeIdx = 0;
  for (int i = 0; i < outMoves.count; ++i)
  {
    const Move m = outMoves.moves[i];

    if (!make_move(board, m))
    {
      continue; // illegal move, do not keep
    }

    bool kingInCheck = isInCheck(board, side);

    unmake_move(board);

    if (!kingInCheck)
    {
      // This move is legal in standard chess; keep it in-place.
      outMoves.moves[writeIdx++] = m;
    }
  }
  outMoves.count = writeIdx;

  // 3) Apply forced-capture rule
  applyCaptureOnlyFilter(outMoves);
}

// --- Public API implementation ---

void validMoveGeneration(const Board &board,
                         Side side,
                         MoveList &outMoves)
{
  validMoveGeneration_ApproachA(board, side, outMoves);
}
