#ifndef MOVE_APPLY_H
#define MOVE_APPLY_H

#include "../board/board.h"
#include "move.h"

// Max search depth / history size
constexpr int MAX_PLY = 256;

// One entry of the undo / history stack
struct UndoState {
    Move move;              // The move that was played

    int  moved_piece_full;   // e.g. WPAWN, WKNIGHT
    int  captured_piece_full;// e.g. BPAWN, BROOK, or 0 if none

    int  old_castling;
    int  old_ep_square;
    int  old_halfmove_clock;
    int  old_fullmove_number;
    Side old_side;

    uint64_t old_zobrist_key;
};

/**
 * Apply a move to the board, updating:
 *  - board.squares[]
 *  - side to move
 *  - castling rights
 *  - en-passant square
 *  - halfmove / fullmove clocks
 *  - Zobrist hash
 * and pushing an UndoState entry on the history stack.
 *
 * Returns false if the move is illegal (e.g. leaves own king in check),
 * in which case the board is restored to its original state.
 */
bool make_move(Board &b, const Move &m);

/**
 * Undo the last call to make_move(), restoring:
 *  - board.squares[]
 *  - side to move
 *  - castling rights
 *  - en-passant square
 *  - halfmove / fullmove clocks
 *  - Zobrist hash
 * from the UndoState stack.
 *
 * Precondition: at least one move has been made (history not empty).
 */
void unmake_move(Board &b);

#endif // MOVE_APPLY_H
