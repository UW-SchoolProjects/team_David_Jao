#ifndef MOVE_H
#define MOVE_H

#include <cstdint>
#include <string>
#include <iosfwd>

// #include "board.h"

// If PieceType is defined elsewhere, remove this and include that header instead.
enum PieceType : uint8_t
{
  EMPTY = 0,
  PAWN = 1,
  KNIGHT = 2,
  BISHOP = 3,
  ROOK = 4,
  QUEEN = 5,
  KING = 6
};

enum MoveFlag : uint8_t
{
  MF_QUIET = 0,
  MF_CAPTURE = 1 << 0,
  MF_DOUBLE_PAWN_PUSH = 1 << 1,
  MF_KING_CASTLE = 1 << 2,
  MF_QUEEN_CASTLE = 1 << 3,
  MF_EN_PASSANT_CAPTURE = 1 << 4,
  MF_PROMOTION = 1 << 5
};

// Enable simple bitwise ops on MoveFlag
inline MoveFlag operator|(MoveFlag a, MoveFlag b)
{
  return static_cast<MoveFlag>(static_cast<uint8_t>(a) | static_cast<uint8_t>(b));
}
inline MoveFlag &operator|=(MoveFlag &a, MoveFlag b)
{
  a = a | b;
  return a;
}
inline bool operator&(MoveFlag a, MoveFlag b)
{
  return (static_cast<uint8_t>(a) & static_cast<uint8_t>(b)) != 0;
}

/**
 * Packed 32-bit move:
 *
 * bits  0–5   from square (0..63)
 * bits  6–11  to square   (0..63)
 * bits 12–15  flags       (MoveFlag, up to 4 bits used)
 * bits 16–19  promotion piece type (PieceType, 0 if none)
 * bits 20–23  captured piece type  (PieceType, 0 if none)
 * bits 24–31  reserved (free for score, ordering, etc.)
 *
 * A Move is immutable after construction: no setters are provided.
 */
class Move
{
public:
  constexpr Move() : value_(0) {}

  constexpr Move(
      int fromSq, // from square (0..63)
      int toSq,   // to square (0..63)
      MoveFlag flags = MF_QUIET,
      PieceType promo = EMPTY,
      PieceType captured = EMPTY)
      : value_(pack(fromSq, toSq, flags, promo, captured))
  {
  }

  // Access raw packed value (if you want to store it directly somewhere)
  constexpr uint32_t raw() const { return value_; }

  // Accessors
  int from() const;
  int to() const;
  MoveFlag flags() const;
  PieceType promotion() const;
  PieceType captured() const;

  bool isCapture() const;
  bool isPromotion() const;
  bool isCastle() const;
  bool isQuiet() const;
  bool isNull() const { return value_ == 0; }

  // Human-readable string, e.g. "e2e4", "e7e8=Q", "O-O", "O-O-O"
  std::string toString() const;

private:
  uint32_t value_;

  // Bit layout constants
  static constexpr uint32_t FROM_MASK = 0x3F;     // 6 bits
  static constexpr uint32_t TO_MASK = 0xFC0;      // bits 6–11
  static constexpr uint32_t FLAGS_MASK = 0xF000;  // bits 12–15
  static constexpr uint32_t PROMO_MASK = 0xF0000; // bits 16–19
  static constexpr uint32_t CAPT_MASK = 0xF00000; // bits 20–23

  static constexpr int TO_SHIFT = 6;
  static constexpr int FLAGS_SHIFT = 12;
  static constexpr int PROMO_SHIFT = 16;
  static constexpr int CAPT_SHIFT = 20;

  static constexpr uint32_t pack(
      int fromSq,
      int toSq,
      MoveFlag flags,
      PieceType promo,
      PieceType captured)
  {
    return (static_cast<uint32_t>(fromSq) & FROM_MASK) | ((static_cast<uint32_t>(toSq) & FROM_MASK) << TO_SHIFT) | ((static_cast<uint32_t>(flags) & 0xF) << FLAGS_SHIFT) | ((static_cast<uint32_t>(promo) & 0xF) << PROMO_SHIFT) | ((static_cast<uint32_t>(captured) & 0xF) << CAPT_SHIFT);
  }
};

// Stream output operator for easy `std::cout << move;`
std::ostream &operator<<(std::ostream &os, const Move &m);

#endif // MOVE_H
