#include "move.h"
#include <ostream>

// --- basic field accessors ---

int Move::from() const
{
  return static_cast<int>(value_ & FROM_MASK);
}

int Move::to() const
{
  return static_cast<int>((value_ & TO_MASK) >> TO_SHIFT);
}

MoveFlag Move::flags() const
{
  return static_cast<MoveFlag>((value_ & FLAGS_MASK) >> FLAGS_SHIFT);
}

PieceType Move::promotion() const
{
  return static_cast<PieceType>((value_ & PROMO_MASK) >> PROMO_SHIFT);
}

PieceType Move::captured() const
{
  return static_cast<PieceType>((value_ & CAPT_MASK) >> CAPT_SHIFT);
}

bool Move::isCapture() const
{
  return flags() & MF_CAPTURE || flags() & MF_EN_PASSANT_CAPTURE;
}

bool Move::isPromotion() const
{
  return flags() & MF_PROMOTION;
}

bool Move::isCastle() const
{
  MoveFlag f = flags();
  return (f & MF_KING_CASTLE) || (f & MF_QUEEN_CASTLE);
}

bool Move::isQuiet() const
{
  return !isCapture() && !isPromotion() && !isCastle() && !(flags() & MF_DOUBLE_PAWN_PUSH);
}

// --- helpers for toString() ---
static char fileChar(int sq)
{
  int file = sq % 8; // 0..7
  return static_cast<char>('a' + file);
}

static char rankChar(int sq)
{
  int rank = sq / 8; // 0..7
  return static_cast<char>('1' + rank);
}

static char promoPieceChar(PieceType pt)
{
  switch (pt)
  {
  case KNIGHT:
    return 'N';
  case BISHOP:
    return 'B';
  case ROOK:
    return 'R';
  case QUEEN:
    return 'Q';
  default:
    return '?';
  }
}

std::string Move::toString() const
{
  // Castling: print O-O or O-O-O
  if (flags() & MF_KING_CASTLE)
  {
    return "O-O";
  }
  if (flags() & MF_QUEEN_CASTLE)
  {
    return "O-O-O";
  }

  int f = from();
  int t = to();

  std::string s;
  s.reserve(6);

  // From square (e.g., "e2")
  s.push_back(fileChar(f));
  s.push_back(rankChar(f));

  // To square (e.g., "e4")
  s.push_back(fileChar(t));
  s.push_back(rankChar(t));

  // Promotion suffix (e.g., "=Q")
  if (isPromotion())
  {
    PieceType pt = promotion();
    s.push_back('=');
    s.push_back(promoPieceChar(pt));
  }

  return s;
}

std::ostream &operator<<(std::ostream &os, const Move &m)
{
  return os << m.toString();
}
