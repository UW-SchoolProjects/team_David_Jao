// Helper to mirror a 0..63 square vertically (for black PST lookup)
static inline int mirrorSquare64(int sq64)
{
  int file = sq64 & 7;  // 0..7
  int rank = sq64 >> 3; // 0..7
  int mirroredRank = 7 - rank;
  return (mirroredRank << 3) | file;
}

