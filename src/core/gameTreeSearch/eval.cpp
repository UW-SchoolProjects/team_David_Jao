// Central closeness in 0..3 (3 = most central on d/e files and 4/5 ranks).
static inline int center_closeness(int sq64)
{
  if (sq64 < 0 || sq64 >= 64)
    return 0;
  int f = sq64 & 7;
  int r = sq64 >> 3;
  int df = std::min(std::abs(f - 3), std::abs(f - 4));
  int dr = std::min(std::abs(r - 3), std::abs(r - 4));
  int cheb = std::max(df, dr);  // 0 in the very center, 3 on the rim
  return std::max(0, 3 - cheb); // 3 (center) .. 0 (edge)
}

static inline int manhattan(int a, int b)
{
  int af = a & 7, ar = a >> 3;
  int bf = b & 7, br = b >> 3;
  return std::abs(af - bf) + std::abs(ar - br);
}

// Pawn attacks from a square (0..63) for the given side.
static inline uint64_t pawn_attacks_from(int sq64, Side side)
{
  if (sq64 < 0 || sq64 >= 64)
    return 0ULL;
  uint64_t bb = 1ULL << sq64;
  constexpr uint64_t FILE_A = 0x0101010101010101ULL;
  constexpr uint64_t FILE_H = 0x8080808080808080ULL;
  if (side == WHITE)
  {
    uint64_t ne = (bb & ~FILE_H) << 9; // from not-H file to NE
    uint64_t nw = (bb & ~FILE_A) << 7; // from not-A file to NW
    return ne | nw;
  }
  else
  {
    uint64_t se = (bb & ~FILE_H) >> 7; // from not-H file to SE
    uint64_t sw = (bb & ~FILE_A) >> 9; // from not-A file to SW
    return se | sw;
  }
}

// Bitboard of all squares attacked by the given side (pseudo-legal).
static uint64_t attack_map(const Board &board, Side side)
{
  uint64_t occ = board.bb_occ;
  uint64_t attacks = 0ULL;

  auto accumulate = [&](uint64_t bb, auto attackFn) {
    while (bb)
    {
      uint64_t lsb = bb & -bb;
      int sq = __builtin_ctzll(lsb);
      bb ^= lsb;
      attacks |= attackFn(sq);
    }
  };

  uint64_t pawns = bb_of(board, (static_cast<int>(side) << 3) | PAWN);
  accumulate(pawns, [&](int sq) { return pawn_attacks_from(sq, side); });

  uint64_t knights = bb_of(board, (static_cast<int>(side) << 3) | KNIGHT);
  accumulate(knights, [&](int sq) { return knightAttacks[sq]; });

  uint64_t bishops = bb_of(board, (static_cast<int>(side) << 3) | BISHOP);
  accumulate(bishops, [&](int sq) { return bishopAttacks(sq, occ); });

  uint64_t rooks = bb_of(board, (static_cast<int>(side) << 3) | ROOK);
  accumulate(rooks, [&](int sq) { return rookAttacks(sq, occ); });

  uint64_t queens = bb_of(board, (static_cast<int>(side) << 3) | QUEEN);
  accumulate(queens, [&](int sq) { return bishopAttacks(sq, occ) | rookAttacks(sq, occ); });

  uint64_t kings = bb_of(board, (static_cast<int>(side) << 3) | KING);
  uint64_t ownOcc = occ_side(board, side);
  accumulate(kings, [&](int sq) { return kingAttacks[sq] & ~ownOcc; });

  return attacks;
}

struct CaptureCandidate
{
  int from;
  int to;
  PieceType mover;
  PieceType victim;
  bool isEnPassant;
};

// Gather pseudo-legal captures for a side (ignores pins/checks).
static void gather_capture_candidates(const Board &board, Side side, std::vector<CaptureCandidate> &out)
{
  uint64_t occ = board.bb_occ;
  Side oppSide = (side == WHITE ? BLACK : WHITE);
  uint64_t oppOcc = occ_side(board, oppSide);
  int epSq64 = (board.ep_square != NO_SQUARE) ? BB_INDEX_FROM_0x88(board.ep_square) : -1;

  auto push_capture = [&](int fromSq, int toSq, PieceType moverType, PieceType victimType, bool isEnPassant) {
    out.push_back({fromSq, toSq, moverType, victimType, isEnPassant});
  };

  auto add_capture = [&](int fromSq, uint64_t targets, PieceType moverType) {
    while (targets)
    {
      uint64_t lsb = targets & -targets;
      int toSq = __builtin_ctzll(lsb);
      targets ^= lsb;
      int to88 = SQ64_to_0x88(toSq);
      int victimPiece = board.squares[to88];
      if (victimPiece == EMPTY)
        continue;
      push_capture(fromSq, toSq, moverType, static_cast<PieceType>(type_of(victimPiece)), false);
    }
  };

  uint64_t pawns = bb_of(board, (static_cast<int>(side) << 3) | PAWN);
  while (pawns)
  {
    uint64_t lsb = pawns & -pawns;
    int fromSq = __builtin_ctzll(lsb);
    pawns ^= lsb;
    uint64_t captures = pawn_attacks_from(fromSq, side) & oppOcc;
    add_capture(fromSq, captures, PAWN);
    if (epSq64 >= 0 && epSq64 < 64)
    {
      int epSq88 = SQ64_to_0x88(epSq64);
      if (IS_ONBOARD(epSq88) && board.squares[epSq88] == EMPTY) {
        int capSq88 = epSq88 + (side == WHITE ? -16 : 16);
        if (IS_ONBOARD(capSq88)) {
          int capPiece = board.squares[capSq88];
          if (capPiece != EMPTY && color_of(capPiece) != side && type_of(capPiece) == PAWN) {
        uint64_t epBB = 1ULL << epSq64;
        if (pawn_attacks_from(fromSq, side) & epBB)
        {
          push_capture(fromSq, epSq64, PAWN, PAWN, true);
        }
          }
        }
      }
    }
  }

  uint64_t knights = bb_of(board, (static_cast<int>(side) << 3) | KNIGHT);
  while (knights)
  {
    uint64_t lsb = knights & -knights;
    int fromSq = __builtin_ctzll(lsb);
    knights ^= lsb;
    uint64_t targets = knightAttacks[fromSq] & oppOcc;
    add_capture(fromSq, targets, KNIGHT);
  }

  uint64_t bishops = bb_of(board, (static_cast<int>(side) << 3) | BISHOP);
  while (bishops)
  {
    uint64_t lsb = bishops & -bishops;
    int fromSq = __builtin_ctzll(lsb);
    bishops ^= lsb;
    uint64_t targets = bishopAttacks(fromSq, occ) & oppOcc;
    add_capture(fromSq, targets, BISHOP);
  }

  uint64_t rooks = bb_of(board, (static_cast<int>(side) << 3) | ROOK);
  while (rooks)
  {
    uint64_t lsb = rooks & -rooks;
    int fromSq = __builtin_ctzll(lsb);
    rooks ^= lsb;
    uint64_t targets = rookAttacks(fromSq, occ) & oppOcc;
    add_capture(fromSq, targets, ROOK);
  }

  uint64_t queens = bb_of(board, (static_cast<int>(side) << 3) | QUEEN);
  while (queens)
  {
    uint64_t lsb = queens & -queens;
    int fromSq = __builtin_ctzll(lsb);
    queens ^= lsb;
    uint64_t targets = (bishopAttacks(fromSq, occ) | rookAttacks(fromSq, occ)) & oppOcc;
    add_capture(fromSq, targets, QUEEN);
  }

}

// Lightweight SEE variant that works on a static board and explicit mover side.
static int static_exchange_eval_side(const Board &board, const CaptureCandidate &c, Side mover)
{
  const Side them = (mover == WHITE ? BLACK : WHITE);
  const int fromSq64 = c.from;
  const int toSq64 = c.to;
  const int capSq88 = SQ64_to_0x88(toSq64);
  const int movingPieceFull = (static_cast<int>(mover) << 3) | static_cast<int>(c.mover);
  int victimPieceFull;
  int victimSq64 = toSq64;
  bool isEnPassant = c.isEnPassant;
  int targetPiece = movingPieceFull;

  auto piece_value = [&](int pt) {
    if (pt < EMPTY || pt > KING)
      return 0;
    return MG_PIECE_VALUE[pt];
  };

  auto promotion_gain = [&](int toSqLocal, PieceType moverPt, Side s) -> int {
    if (moverPt != PAWN)
      return 0;
    int rank = toSqLocal >> 3;
    if ((s == WHITE && rank == 7) || (s == BLACK && rank == 0))
    {
      return MG_PIECE_VALUE[QUEEN] - MG_PIECE_VALUE[PAWN];
    }
    return 0;
  };

  if (!IS_ONBOARD(capSq88))
    return 0;

  if (isEnPassant)
  {
    int capturedSq88 = capSq88 + (mover == WHITE ? -16 : 16);
    if (!IS_ONBOARD(capturedSq88))
      return 0;
    if (capturedSq88 < 0 || capturedSq88 >= BOARD_SIZE)
      return 0;
    victimPieceFull = board.squares[capturedSq88];
    if (victimPieceFull == EMPTY || type_of(victimPieceFull) != PAWN)
      return 0;
    victimSq64 = BB_INDEX_FROM_0x88(capturedSq88);
    if (victimSq64 < 0 || victimSq64 >= 64)
      return 0;
  }
  else
  {
    victimPieceFull = board.squares[capSq88];
    victimSq64 = toSq64;
    if (victimSq64 < 0 || victimSq64 >= 64)
      return 0;
  }

  if (victimPieceFull == EMPTY)
    return 0;

  uint64_t occ = board.bb_occ;
  uint64_t bb[16];
  for (int i = 0; i < 16; ++i)
    bb[i] = board.bb_piece[i];

  auto clear_bit = [](uint64_t &b, int sq64) {
    if (sq64 >= 0 && sq64 < 64)
      b &= ~(1ULL << sq64);
  };
  auto set_bit = [](uint64_t &b, int sq64) {
    if (sq64 >= 0 && sq64 < 64)
      b |= (1ULL << sq64);
  };
  auto clear_occ = [&](int sq64) {
    if (sq64 >= 0 && sq64 < 64)
      occ &= ~(1ULL << sq64);
  };
  auto set_occ = [&](int sq64) {
    if (sq64 >= 0 && sq64 < 64)
      occ |= (1ULL << sq64);
  };

  auto promote_if_applicable = [&](int pieceIdx, int sq64, Side owner) -> int {
    if (type_of(pieceIdx) != PAWN)
      return pieceIdx;
    int rank = sq64 >> 3;
    if ((owner == WHITE && rank == 7) || (owner == BLACK && rank == 0))
    {
      clear_bit(bb[pieceIdx], sq64);
      int queenIdx = (static_cast<int>(owner) << 3) | QUEEN;
      set_bit(bb[queenIdx], sq64);
      return queenIdx;
    }
    return pieceIdx;
  };

  // Remove moving piece from origin
  clear_bit(bb[movingPieceFull], fromSq64);
  clear_occ(fromSq64);

  // Remove captured victim (may differ from target square in en passant)
  clear_bit(bb[victimPieceFull], victimSq64);
  clear_occ(victimSq64);

  // Place moving piece on target square
  set_bit(bb[movingPieceFull], toSq64);
  set_occ(toSq64);
  targetPiece = promote_if_applicable(targetPiece, toSq64, mover);

  int gains[32];
  int captureValue = piece_value(type_of(victimPieceFull));
  int initialPromo = promotion_gain(toSq64, c.mover, mover);
  gains[0] = captureValue + initialPromo;
  int depth = 0;

  Side side = them; // opponent to recapture

  auto pawn_attackers_to = [](int sq, Side s) {
    uint64_t bbSq = 1ULL << sq;
    constexpr uint64_t FILE_A = 0x0101010101010101ULL;
    constexpr uint64_t FILE_H = 0x8080808080808080ULL;
    if (s == WHITE)
    {
      uint64_t fromEast = (bbSq >> 9) & ~FILE_H; // from file+1
      uint64_t fromWest = (bbSq >> 7) & ~FILE_A; // from file-1
      return fromEast | fromWest;
    }
    else
    {
      uint64_t fromWest = (bbSq << 9) & ~FILE_A; // from file-1
      uint64_t fromEast = (bbSq << 7) & ~FILE_H; // from file+1
      return fromWest | fromEast;
    }
  };

  auto attackers_of_side = [&](Side s, uint64_t occBB, uint64_t pieces[]) -> uint64_t {
    uint64_t occAdj = occBB;
    if (c.isEnPassant)
    {
      int capBehind88 = SQ64_to_0x88(toSq64) + (mover == WHITE ? -16 : 16);
      int capBehind64 = IS_ONBOARD(capBehind88) ? BB_INDEX_FROM_0x88(capBehind88) : -1;
      if (capBehind64 >= 0 && capBehind64 < 64)
        occAdj &= ~(1ULL << capBehind64);
    }
    uint64_t pawns = pieces[(static_cast<int>(s) << 3) | PAWN];
    uint64_t knights = pieces[(static_cast<int>(s) << 3) | KNIGHT];
    uint64_t bishops = pieces[(static_cast<int>(s) << 3) | BISHOP];
    uint64_t rooks = pieces[(static_cast<int>(s) << 3) | ROOK];
    uint64_t queens = pieces[(static_cast<int>(s) << 3) | QUEEN];
    uint64_t kings = pieces[(static_cast<int>(s) << 3) | KING];

    uint64_t bbTarget = 1ULL << toSq64;
    uint64_t raw = 0ULL;
    raw |= pawn_attackers_to(toSq64, s) & pawns;
    raw |= knightAttacks[toSq64] & knights;
    uint64_t bishopRay = bishopAttacks(toSq64, occAdj);
    raw |= bishopRay & (bishops | queens);
    uint64_t rookRay = rookAttacks(toSq64, occAdj);
    raw |= rookRay & (rooks | queens);
    raw |= kingAttacks[toSq64] & kings;
    raw &= ~bbTarget; // exclude piece currently on target

    // Filter out pinned attackers (removing fromSq while keeping target occupied must not expose own king).
    if (kings == 0)
      return raw; // no king info; skip filter
    int kingSq = __builtin_ctzll(kings);
    uint64_t oppBish = pieces[((static_cast<int>(s) ^ 1) << 3) | BISHOP] | pieces[((static_cast<int>(s) ^ 1) << 3) | QUEEN];
    uint64_t oppRook = pieces[((static_cast<int>(s) ^ 1) << 3) | ROOK] | pieces[((static_cast<int>(s) ^ 1) << 3) | QUEEN];

    uint64_t filtered = 0ULL;
    uint64_t tmp = raw;
    while (tmp)
    {
      uint64_t lsb = tmp & -tmp;
      int fromSq = __builtin_ctzll(lsb);
      tmp ^= lsb;

      uint64_t occTest = (occBB & ~(1ULL << fromSq)) | bbTarget; // simulate capture (move attacker onto target)
      bool kingDiag = (bishopAttacks(kingSq, occTest) & oppBish) != 0ULL;
      bool kingOrth = (rookAttacks(kingSq, occTest) & oppRook) != 0ULL;
      if (!(kingDiag || kingOrth))
      {
        filtered |= lsb;
      }
    }
    return filtered;
  };

  while (true)
  {
    uint64_t attackers = attackers_of_side(side, occ, bb);
    if (!attackers)
      break;

    // Select least valuable attacker of this side
    int fromSq = -1;
    int attackerPiece = -1;
    auto pick_attacker = [&](PieceType pt, uint64_t mask) -> bool {
      if (mask == 0)
        return false;
      fromSq = __builtin_ctzll(mask);
      attackerPiece = (static_cast<int>(side) << 3) | static_cast<int>(pt);
      return true;
    };

    uint64_t mask;
    mask = attackers & bb[(static_cast<int>(side) << 3) | PAWN];
    if (pick_attacker(PAWN, mask))
      goto found_attacker;
    mask = attackers & bb[(static_cast<int>(side) << 3) | KNIGHT];
    if (pick_attacker(KNIGHT, mask))
      goto found_attacker;
    mask = attackers & bb[(static_cast<int>(side) << 3) | BISHOP];
    if (pick_attacker(BISHOP, mask))
      goto found_attacker;
    mask = attackers & bb[(static_cast<int>(side) << 3) | ROOK];
    if (pick_attacker(ROOK, mask))
      goto found_attacker;
    mask = attackers & bb[(static_cast<int>(side) << 3) | QUEEN];
    if (pick_attacker(QUEEN, mask))
      goto found_attacker;
    mask = attackers & bb[(static_cast<int>(side) << 3) | KING];
    if (pick_attacker(KING, mask))
      goto found_attacker;

  found_attacker:
    if (attackerPiece == -1)
      break;

    depth += 1;
    if (depth >= static_cast<int>(sizeof(gains) / sizeof(gains[0])))
      break; // safety guard

    int takeVal = piece_value(type_of(targetPiece));
    int capPromo = promotion_gain(toSq64, static_cast<PieceType>(type_of(attackerPiece)), side);
    gains[depth] = takeVal + capPromo - gains[depth - 1];

    // Capture: remove current target piece, move attacker onto target
    clear_bit(bb[targetPiece], toSq64);
    clear_bit(bb[attackerPiece], fromSq);
    clear_occ(toSq64);
    clear_occ(fromSq);
    targetPiece = attackerPiece;
    set_bit(bb[targetPiece], toSq64);
    set_occ(toSq64);
    Side capturingSide = side;
    targetPiece = promote_if_applicable(targetPiece, toSq64, capturingSide);
    side = (side == WHITE ? BLACK : WHITE);
  }

  // Propagate best achievable scores backward
  while (--depth >= 0)
  {
    gains[depth] = std::max(-gains[depth + 1], gains[depth]);
  }

  return gains[0];
}

// -----------------------------------------------------------------------------
// Core evaluation
// - Returns score from side-to-move perspective.
// - Positive = good for side to move.
// -----------------------------------------------------------------------------

int basicEvaluate(const Board &board)
{
  int mgScore = 0; // Middlegame score (White POV)
  int egScore = 0; // Endgame score   (White POV)

  int pieceCount[2][7] = {{0}};
  int whiteBishops = 0;
  int blackBishops = 0;
  int kingSq[2] = {-1, -1};

  int phase = 0; // 0..PHASE_TOTAL

  // --- Scan all 0x88 squares ---
  for (int sq = 0; sq < BOARD_SIZE; ++sq)
  {
    if (!IS_ONBOARD(sq))
      continue;

    int piece = board.squares[sq];
    if (piece == EMPTY)
      continue;

    int pt = type_of(piece);    // PieceType 1..6
    int side = color_of(piece); // WHITE or BLACK

    // Skip EMPTY or unexpected values defensively
    if (pt < PAWN || pt > KING)
      continue;

    pieceCount[side][pt]++;

    // Map 0x88 square to 0..63 index
    int sq64 = BB_INDEX_FROM_0x88(sq);

    // Use white-oriented PSTs and mirror for black
    int idx = (side == WHITE) ? sq64 : mirrorSquare64(sq64);

    int mgVal = MG_PIECE_VALUE[pt] + MG_PST[pt][idx];
    int egVal = EG_PIECE_VALUE[pt] + EG_PST[pt][idx];

    // Phase contribution (based on piece type only)
    phase += PHASE_WEIGHT[pt];

    int close = center_closeness(sq64);
    int mgAdj = close * CENTER_MG_WEIGHT[pt];
    int egAdj = close * CENTER_EG_WEIGHT[pt];

    if (side == WHITE)
    {
      mgScore += mgVal + mgAdj;
      egScore += egVal + egAdj;
      if (pt == BISHOP)
        ++whiteBishops;
      if (pt == KING)
        kingSq[WHITE] = sq64;
    }
    else
    {
      mgScore -= mgVal + mgAdj;
      egScore -= egVal + egAdj;
      if (pt == BISHOP)
        ++blackBishops;
      if (pt == KING)
        kingSq[BLACK] = sq64;
    }
  }

  // Clamp phase to [0, PHASE_TOTAL]
  phase = std::min(phase, PHASE_TOTAL);
  // phase = PHASE_TOTAL → "pure" middlegame
  // phase = 0           → "pure" endgame

  // --- Bishop pair bonus (applied equally to MG and EG) ---
  if (whiteBishops >= 2)
  {
    mgScore += BISHOP_PAIR_BONUS;
    egScore += BISHOP_PAIR_BONUS;
  }
  if (blackBishops >= 2)
  {
    mgScore -= BISHOP_PAIR_BONUS;
    egScore -= BISHOP_PAIR_BONUS;
  }

  if (KING_PROX_BONUS != 0 && kingSq[WHITE] != -1 && kingSq[BLACK] != -1)
  {
    const int dist = manhattan(kingSq[WHITE], kingSq[BLACK]);
    const int prox = std::max(0, KING_PROX_DIST_BASE - dist);
    if (prox > 0)
    {
      const int egWeight = PHASE_TOTAL - phase;
      const long long term = static_cast<long long>(prox) * egWeight * KING_PROX_BONUS;
      const int proxTerm = static_cast<int>(std::max<long long>(std::min<long long>(term / std::max(1, PHASE_TOTAL), INT_MAX), INT_MIN));
      egScore += proxTerm;
    }
  }

  // --- Phase tapered blend ---
  int scoreWhite =
      (mgScore * phase + egScore * (PHASE_TOTAL - phase)) / std::max(1, PHASE_TOTAL);

  // --- Tempo bonus ---
  if (board.side == WHITE)
    scoreWhite += TEMPO_BONUS;
  else
    scoreWhite -= TEMPO_BONUS;

  // Phase weight for MG-only terms (fade after EG threshold)
  int mgPhaseScaled = (phase >= EG_PHASE_THRESHOLD) ? 100 : (phase * 100) / std::max(1, EG_PHASE_THRESHOLD);
  mgPhaseScaled = std::max(0, std::min(100, mgPhaseScaled));

  Side stm = static_cast<Side>(board.side);
  Side opp = (stm == WHITE ? BLACK : WHITE);

  int matScore[2] = {0, 0};
  for (int s = 0; s < 2; ++s)
  {
    for (int pt = PAWN; pt <= QUEEN; ++pt)
    {
      matScore[s] += pieceCount[s][pt] * MG_PIECE_VALUE[pt];
    }
  }

  // ---------------------------------------------------------------------------
  // Opponent king mobility (Mk) and tactical bonuses
  // ---------------------------------------------------------------------------
  uint64_t stmAttacks = attack_map(board, stm);
  int mk = 0;
  bool oppInCheck = false;
  {
    uint64_t oppKingBB = bb_of(board, (static_cast<int>(opp) << 3) | KING);
    if (oppKingBB)
    {
      int ksq = __builtin_ctzll(oppKingBB);
      oppInCheck = (stmAttacks & (1ULL << ksq)) != 0ULL;
      uint64_t raw = kingAttacks[ksq];
      raw &= ~occ_side(board, opp);
      uint64_t legal = 0ULL;
      uint64_t cand = raw;
      uint64_t stmPawns = bb_of(board, (static_cast<int>(stm) << 3) | PAWN);
      uint64_t stmPawnAttacks = 0ULL;
      while (stmPawns)
      {
        uint64_t lsb = stmPawns & -stmPawns;
        int sq = __builtin_ctzll(lsb);
        stmPawns ^= lsb;
        stmPawnAttacks |= pawn_attacks_from(sq, stm);
      }
      uint64_t stmKnights = bb_of(board, (static_cast<int>(stm) << 3) | KNIGHT);
      uint64_t stmBishops = bb_of(board, (static_cast<int>(stm) << 3) | BISHOP);
      uint64_t stmRooks = bb_of(board, (static_cast<int>(stm) << 3) | ROOK);
      uint64_t stmQueens = bb_of(board, (static_cast<int>(stm) << 3) | QUEEN);
      uint64_t stmKingBB = bb_of(board, (static_cast<int>(stm) << 3) | KING);
      while (cand)
      {
        uint64_t lsb = cand & -cand;
        int to = __builtin_ctzll(lsb);
        cand ^= lsb;
      uint64_t occ_to = board.bb_occ;
      occ_to &= ~(1ULL << ksq);
      occ_to &= ~(1ULL << to); // remove captured occupant on target
      occ_to |= (1ULL << to);  // place king on target
      bool unsafe = false;
      if (stmPawnAttacks & (1ULL << to))
      {
        unsafe = true;
      }
      if (!unsafe && (knightAttacks[to] & stmKnights))
      {
        unsafe = true;
      }
      if (!unsafe && stmKingBB && (kingAttacks[to] & stmKingBB))
      {
        unsafe = true;
      }
      if (!unsafe && (rookAttacks(to, occ_to) & (stmRooks | stmQueens)))
      {
        unsafe = true;
      }
      if (!unsafe && (bishopAttacks(to, occ_to) & (stmBishops | stmQueens)))
      {
        unsafe = true;
      }
      if (!unsafe)
      {
        legal |= lsb;
      }
      }
      if (stmKingBB)
      {
        int stmKsq = __builtin_ctzll(stmKingBB);
        legal &= ~kingAttacks[stmKsq];
      }
      legal &= ~(1ULL << ksq);
      mk = popcount(legal);
    }
  }
  int mkMissing = std::max(0, MK_TARGET - mk);
  int mkBonus = mkMissing * MK_MISSING_SQUARE_WEIGHT;
  if (oppInCheck)
    mkBonus = (mkBonus * MK_IN_CHECK_SCALE_PCT) / 100;
  if (mkBonus > MK_BONUS_MAX)
    mkBonus = MK_BONUS_MAX;
  scoreWhite += (stm == WHITE ? mkBonus : -mkBonus);

  if (!oppInCheck && mk <= CONSTRAINT_TRIGGER_MK_MAX)
  {
    int totalNonKing =
        popcount(bb_of(board, WPAWN) | bb_of(board, WKNIGHT) | bb_of(board, WBISHOP) | bb_of(board, WROOK) |
                 bb_of(board, WQUEEN)) +
        popcount(bb_of(board, BPAWN) | bb_of(board, BKNIGHT) | bb_of(board, BBISHOP) | bb_of(board, BROOK) |
                 bb_of(board, BQUEEN));
    int richnessScale = std::max(
        RICHNESS_MIN,
        RICHNESS_BASE_MAX - std::min(RICHNESS_PIECES_CAP, totalNonKing) * RICHNESS_PIECE_PENALTY);
    int base = (CONSTRAINT_BASE * mgPhaseScaled) / 100;
    int constraint = std::min(base, richnessScale);
    if (constraint > CONSTRAINT_CAP)
      constraint = CONSTRAINT_CAP;
    scoreWhite += (stm == WHITE ? constraint : -constraint);
  }

  // ---------------------------------------------------------------------------
  // Trade risk: penalize forced bad captures with high-value pieces (MG heavy)
  // ---------------------------------------------------------------------------
  std::vector<CaptureCandidate> stmCaps;
  gather_capture_candidates(board, stm, stmCaps);
  int tradePenalty = 0;
  for (const auto &c : stmCaps)
  {
    if (c.mover == KING)
      continue;
    int see = static_exchange_eval_side(board, c, stm);
    int attackerVal = MG_PIECE_VALUE[c.mover];
    if (see < 0 && attackerVal >= MG_PIECE_VALUE[KNIGHT])
      tradePenalty += (-see) + attackerVal / TRADE_ATTACKER_NEG_SEE_DIV;
    if (c.mover == QUEEN && c.victim == PAWN)
      tradePenalty += TRADE_QUEEN_PAWN_PENALTY; // discourage queen pawn grabs under compulsion
    if (MG_PIECE_VALUE[c.victim] < attackerVal / TRADE_SMALL_VICTIM_DIV && see <= 0)
      tradePenalty += attackerVal / TRADE_ATTACKER_SMALL_VICTIM_DIV;
  }
  tradePenalty = (tradePenalty * mgPhaseScaled) / 100;
  tradePenalty = (tradePenalty * TRADE_RISK_SCALE_PCT) / 100;
  if (tradePenalty)
    scoreWhite += (stm == WHITE ? -tradePenalty : tradePenalty);

  // ---------------------------------------------------------------------------
  // Mobility: opponent safe captures are bad, self-exposing captures are good.
  // ---------------------------------------------------------------------------
  std::vector<CaptureCandidate> oppCaps;
  gather_capture_candidates(board, opp, oppCaps);
  int safeCaps = 0;
  int riskyCaps = 0;
  for (const auto &c : oppCaps)
  {
    int see = static_exchange_eval_side(board, c, opp);
    if (see >= 0)
      ++safeCaps;
    else
      ++riskyCaps;
  }
  int mobilityBase = riskyCaps * MOBILITY_RISKY_CAP_WEIGHT - safeCaps * MOBILITY_SAFE_CAP_WEIGHT;
  mobilityBase = (mobilityBase * mgPhaseScaled) / 100;
  if (mobilityBase)
    scoreWhite += (opp == WHITE ? mobilityBase : -mobilityBase);

  // ---------------------------------------------------------------------------
  // Endgame KingAttackPhase: king activity + boosted Mk when mate is realistic
  // ---------------------------------------------------------------------------
  int oppNonKing = pieceCount[opp][PAWN] + pieceCount[opp][KNIGHT] + pieceCount[opp][BISHOP] +
                   pieceCount[opp][ROOK] + pieceCount[opp][QUEEN];
  bool oppMinimal = pieceCount[opp][PAWN] == 0 && oppNonKing <= KING_ATTACK_OPP_NONKING_MAX;
  bool stmHasMatingMaterial =
      pieceCount[stm][QUEEN] > 0 || pieceCount[stm][ROOK] > 0 || pieceCount[stm][PAWN] > 0 ||
      pieceCount[stm][BISHOP] >= 2 || (pieceCount[stm][BISHOP] == 1 && pieceCount[stm][KNIGHT] >= 1);
  bool kingAttackPhase = (phase <= EG_PHASE_THRESHOLD) && stmHasMatingMaterial && oppMinimal &&
                         kingSq[stm] != -1 && kingSq[opp] != -1;
  if (kingAttackPhase)
  {
    int kingDist = manhattan(kingSq[stm], kingSq[opp]);
    int kingActivity = std::max(0, KING_ATTACK_ACTIVITY_DIST_BASE - kingDist) * KING_ATTACK_ACTIVITY_WEIGHT;
    int nearestAttacker = 99;
    uint64_t attackers = bb_of(board, (static_cast<int>(stm) << 3) | QUEEN) |
                         bb_of(board, (static_cast<int>(stm) << 3) | ROOK) |
                         bb_of(board, (static_cast<int>(stm) << 3) | BISHOP) |
                         bb_of(board, (static_cast<int>(stm) << 3) | KNIGHT);
    while (attackers)
    {
      uint64_t lsb = attackers & -attackers;
      int sq = __builtin_ctzll(lsb);
      attackers ^= lsb;
      int d = manhattan(sq, kingSq[opp]);
      if (d < nearestAttacker)
        nearestAttacker = d;
    }
    int attackerPull = (nearestAttacker != 99)
                           ? std::max(0, KING_ATTACK_ATTACKER_PULL_DIST_BASE - nearestAttacker) * KING_ATTACK_ATTACKER_PULL_WEIGHT
                           : 0;
    int kingAttackBonus = kingActivity + attackerPull;
    int boostedMk = mkBonus / KING_ATTACK_BOOSTED_MK_DIV; // extra weight beyond the base Mk bonus
    scoreWhite += (stm == WHITE ? boostedMk : -boostedMk);
    scoreWhite += (stm == WHITE ? kingAttackBonus : -kingAttackBonus);
  }

  // If we have a clear material advantage in late phase, encourage king aggression.
  if (kingSq[stm] != -1 && kingSq[opp] != -1)
  {
    int matDiff = matScore[stm] - matScore[opp];
    if (phase <= EG_PHASE_THRESHOLD + KING_AGGRESSION_PHASE_MARGIN &&
        matDiff >= KING_AGGRESSION_MAT_DIFF_THRESHOLD)
    {
      int kingDist = manhattan(kingSq[stm], kingSq[opp]);
      int aggression = std::max(0, KING_AGGRESSION_DIST_BASE - kingDist) * KING_AGGRESSION_WEIGHT;
      scoreWhite += (stm == WHITE ? aggression : -aggression);
    }
  }

  // Encourage advancing pawns toward promotion (White POV).
  {
    uint64_t wp = bb_of(board, WPAWN);
    while (wp)
    {
      uint64_t lsb = wp & -wp;
      int sq = __builtin_ctzll(lsb);
      wp ^= lsb;
      int rank = sq >> 3;
      scoreWhite += rank * PAWN_ADVANCE_RANK_WEIGHT; // small bonus per rank advanced
    }
    uint64_t bp = bb_of(board, BPAWN);
    while (bp)
    {
      uint64_t lsb = bp & -bp;
      int sq = __builtin_ctzll(lsb);
      bp ^= lsb;
      int rankFromWhite = 7 - (sq >> 3);
      scoreWhite -= rankFromWhite * PAWN_ADVANCE_RANK_WEIGHT;
    }
  }

  // --- 50-move proximity penalty (apply in side-to-move POV) ---
  int sideToMovePenalty = 0;
  {
    int hm = board.halfmove_clock;
    if (hm > FIFTY_MOVE_THRESHOLD)
    {
      sideToMovePenalty = (hm - FIFTY_MOVE_THRESHOLD) * FIFTY_MOVE_PENALTY_PER_PLY;
    }
  }

  // Convert from White POV to side-to-move POV:
  // Positive = good for side to move.
  int stmScore = (board.side == WHITE) ? scoreWhite : -scoreWhite;

  stmScore += EVAL_BIAS;

  // Penalize side to move equally in either case
  stmScore -= sideToMovePenalty;
  return stmScore;
}
