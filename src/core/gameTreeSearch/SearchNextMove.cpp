// Simple material draw detector (insufficient material).
bool isInsufficientMaterial(const Board &b)
{
  // If any pawn, rook, or queen exists, it's not insufficient.
  auto any = [&](int piece) { return bb_of(b, piece) != 0ULL; };
  if (any(WPAWN) || any(BPAWN) || any(WROOK) || any(BROOK) || any(WQUEEN) || any(BQUEEN))
    return false;

  bool whiteMinor = bb_of(b, WKNIGHT) || bb_of(b, WBISHOP);
  bool blackMinor = bb_of(b, BKNIGHT) || bb_of(b, BBISHOP);
  int whiteMinorCount = popcount(bb_of(b, WKNIGHT)) + popcount(bb_of(b, WBISHOP));
  int blackMinorCount = popcount(bb_of(b, BKNIGHT)) + popcount(bb_of(b, BBISHOP));

  // Only kings
  if (!whiteMinor && !blackMinor)
    return true;

  // King + single minor vs king
  if ((whiteMinorCount == 1 && blackMinorCount == 0) || (whiteMinorCount == 0 && blackMinorCount == 1))
    return true;

  // King + bishop vs king + bishop with bishops on same color squares.
  if (whiteMinorCount == 1 && blackMinorCount == 1 &&
      bb_of(b, WBISHOP) && bb_of(b, BBISHOP))
  {
    // Bishops on same color? Use square color of lsb.
    auto lsb = [](uint64_t bb) { return __builtin_ctzll(bb); };
    int wSq = lsb(bb_of(b, WBISHOP));
    int bSq = lsb(bb_of(b, BBISHOP));
    bool wDark = ((wSq & 1) ^ ((wSq >> 3) & 1)) != 0;
    bool bDark = ((bSq & 1) ^ ((bSq >> 3) & 1)) != 0;
    if (wDark == bDark)
      return true;
  }

  return false;
}

// PV table: pvTable[ply][i] is the i-th move in the PV at search ply `ply`.
static Move pvTable[MAX_PLY][MAX_PLY];

// PV length per ply
static int pvLength[MAX_PLY];

int search(Board &board,
           int depth,
           int alpha,
           int beta,
           int ply,
           EvalFn evalFn)
{
#ifdef ENGINE_LOGGING
  log_msg("search start depth=" + std::to_string(depth) +
          " alpha=" + std::to_string(alpha) +
          " beta=" + std::to_string(beta) +
          " ply=" + std::to_string(ply));
#endif
  const int alphaOrig = alpha;
  const uint64_t key = board.zobrist_key;

  int ttScore = 0;
  Move ttMove;
  if (TT.probe(key, depth, alpha, beta, ply, ttScore, ttMove))
  {
    // Maintain PV on TT hit
    pvLength[ply] = 0;
    if (!ttMove.isNull())
    {
      pvTable[ply][0] = ttMove;
      pvLength[ply] = 1;
    }
    return ttScore;
  }

  // Initialize PV length for this ply (no moves yet)
  pvLength[ply] = 0;

  // --- Depth / leaf handling ---
  // 50-move rule or insufficient material → draw
  if (board.halfmove_clock >= 100 || isInsufficientMaterial(board))
  {
    TT.store(key, depth, 0, TTFlag::EXACT, Move(), ply);
    return 0;
  }

  if (depth <= 0)
  {
    return qsearch(board, alpha, beta, ply, evalFn);
  }

  // --- Generate all legal moves for the side to move ---
  MoveList moves;
  get_variant_moves(board, static_cast<Side>(board.side), moves);

  if (moves.empty())
  {
    Side sideToMove = static_cast<Side>(board.side);

    if (isInCheck(board, sideToMove))
    {
      // Checkmate: side to move has no moves and is in check.
      // Encode mate as a large negative score, slightly adjusted by ply
      // so closer mates are better (for the winning side).
      int mateScore = -SCORE_MATE + ply;
      TT.store(key, depth, mateScore, TTFlag::EXACT, Move(), ply);
      return mateScore;
    }
    else
    {
      // Stalemate: draw
      TT.store(key, depth, 0, TTFlag::EXACT, Move(), ply);
      return 0;
    }
  }

  int bestScore = -SCORE_INF;
  Move bestMove; // for PV / TT (not used directly by caller)
  bool didCutoff = false;

  // Hash move ordering: search TT move first if present.
  if (!ttMove.isNull())
  {
    for (int i = 0; i < moves.count; ++i)
    {
      if (moves.moves[i].raw() == ttMove.raw())
      {
        std::swap(moves.moves[0], moves.moves[i]);
        break;
      }
    }
  }
  else
  {
    // Simple ordering: captures first using MVV-LVA, then quiets.
    static const int piece_values[] = {0, 100, 320, 330, 500, 900, 10000};
    std::stable_sort(moves.moves, moves.moves + moves.count, [&](const Move &a, const Move &b) {
      const bool ac = a.isCapture();
      const bool bc = b.isCapture();
      if (ac != bc) return ac; // captures before quiets

      if (ac)
      {
        int victim_a = piece_values[a.captured()];
        int victim_b = piece_values[b.captured()];
        if (victim_a != victim_b) return victim_a > victim_b;

        int attacker_a = piece_values[type_of(board.squares[SQ64_to_0x88(a.from())])];
        int attacker_b = piece_values[type_of(board.squares[SQ64_to_0x88(b.from())])];
        return attacker_a < attacker_b;
      }

      return false; // keep original order for quiets
    });
  }

  for (int i = 0; i < moves.count; ++i)
  {
    Move m = moves.moves[i];

    if (!make_move(board, m))
      continue; // illegal move; skip

    // Negamax: flip perspective and bounds
    int score = -search(board, depth - 1, -beta, -alpha, ply + 1, evalFn);

    unmake_move(board);

    if (score > bestScore)
    {
      bestScore = score;
      bestMove = m;

      // --- PV update: this move becomes first move of new PV at this ply ---
      pvTable[ply][0] = m;
      pvLength[ply] = pvLength[ply + 1] + 1;

      for (int j = 0; j < pvLength[ply + 1]; ++j)
      {
        pvTable[ply][j + 1] = pvTable[ply + 1][j];
      }
    }

    if (bestScore > alpha)
    {
      alpha = bestScore;
      // TODO (PV-node info for TT, if desired)
    }

    // Alpha-beta cutoff
    if (alpha >= beta)
    {
      // Store cutoff as LOWERBOUND with the move that caused it.
      bestMove = m;
      TT.store(key, depth, alpha, TTFlag::LOWERBOUND, bestMove, ply);
      didCutoff = true;
      break;
    }
  }

  // Store result in TT with appropriate flag if no earlier cutoff store.
  if (!didCutoff)
  {
    TTFlag storeFlag = TTFlag::EXACT;
    if (bestScore <= alphaOrig)
    {
      storeFlag = TTFlag::UPPERBOUND;
    }
    TT.store(key, depth, bestScore, storeFlag, bestMove, ply);
  }

  return bestScore;
}

Move getBestMove(Board &board, int maxDepth, EvalFn evalFn)
{
#ifdef ENGINE_LOGGING
  log_msg("getBestMove start maxDepth=" + std::to_string(maxDepth));
#endif
  Move bestMove;     // move to return
  int bestScore = 0; // last stable root score
  bool havePV = false;

  // Iterative deepening loop: depths 1..maxDepth
  for (int depth = 1; depth <= maxDepth; ++depth)
  {
    int alpha, beta;
    int score;

    if (depth == 1)
    {
      // First iteration: full-window search.
      alpha = -SCORE_INF;
      beta = SCORE_INF;
      score = search(board, depth, alpha, beta, /*ply=*/0, evalFn);
    }
    else
    {
      alpha = bestScore - ASP_WINDOW;
      beta = bestScore + ASP_WINDOW;

      // First try with the narrow window
      score = search(board, depth, alpha, beta, /*ply=*/0, evalFn);

      // If we fail low or high, re-search with full window
      if (score <= alpha || score >= beta)
      {
        alpha = -SCORE_INF;
        beta = SCORE_INF;
        score = search(board, depth, alpha, beta, /*ply=*/0, evalFn);
      }
    }

    // After search, PV for this depth is in pvTable[0]
    if (pvLength[0] > 0)
    {
      bestMove = pvTable[0][0];
      bestScore = score;
      havePV = true;

      // (Optional) You can print or log the PV line here for debugging:
      // std::cout << "info depth " << depth << " score cp " << bestScore << " pv ";
      // for (int i = 0; i < pvLength[0]; ++i) {
      //   std::cout << pvTable[0][i].toString() << ' ';
      // }
      // std::cout << std::endl;
    }
    else
    {
      // No PV at this depth: no legal moves (mate/stalemate).
      // We can break early, as deeper searches won't change that.
      break;
    }
  }

  if (!havePV)
  {
    // No legal moves from the start position.
    return Move(); // null move; caller can interpret as game over.
  }

  return bestMove;
}
