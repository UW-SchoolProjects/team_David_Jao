// --- Material helpers for pruning heuristics ---

static inline int count_side_pawns(const Board &b, Side s)
{
  return popcount(bb_of(b, (static_cast<int>(s) << 3) | PAWN));
}

static inline int count_side_nonking(const Board &b, Side s)
{
  int idxBase = static_cast<int>(s) << 3;
  int pawns   = popcount(bb_of(b, idxBase | PAWN));
  int knights = popcount(bb_of(b, idxBase | KNIGHT));
  int bishops = popcount(bb_of(b, idxBase | BISHOP));
  int rooks   = popcount(bb_of(b, idxBase | ROOK));
  int queens  = popcount(bb_of(b, idxBase | QUEEN));
  return pawns + knights + bishops + rooks + queens;
}

static inline bool has_enough_material_for_null(const Board &b, Side s)
{
  int idxBase = static_cast<int>(s) << 3;
  int pawns   = popcount(bb_of(b, idxBase | PAWN));
  int rooks   = popcount(bb_of(b, idxBase | ROOK));
  int queens  = popcount(bb_of(b, idxBase | QUEEN));
  int minors  = popcount(bb_of(b, idxBase | KNIGHT)) + popcount(bb_of(b, idxBase | BISHOP));
  // Allow null only with a pawn, any heavy piece, or at least three minors.
  return pawns > 0 || rooks > 0 || queens > 0 || minors >= 3;
}

static inline bool is_clear_endgame_for_null(const Board &b)
{
  int totalQueens = popcount(bb_of(b, WQUEEN)) + popcount(bb_of(b, BQUEEN));
  int totalRooks  = popcount(bb_of(b, WROOK))  + popcount(bb_of(b, BROOK));
  int totalPawns  = popcount(bb_of(b, WPAWN))  + popcount(bb_of(b, BPAWN));
  return totalQueens == 0 && totalRooks <= 1 && totalPawns <= 6;
}

// Lightweight material values for heuristics (SEE placeholder)
static inline int heuristic_piece_value(int piece)
{
  // Index assumes PieceType encoding 0..6 (EMPTY..KING)
  static const int vals[] = {0, 100, 320, 330, 500, 900, 10000};
  if (piece < 0 || piece >= static_cast<int>(sizeof(vals) / sizeof(vals[0]))) return 0;
  return vals[piece];
}

// Bitboard file masks for pawn attack helpers
static constexpr uint64_t FILE_A = 0x0101010101010101ULL;
static constexpr uint64_t FILE_H = 0x8080808080808080ULL;

// Return bitboard of pawn attackers (of `side`) to square `sq` (0..63).
static inline uint64_t pawn_attackers_to(int sq, Side side)
{
  uint64_t bb = 1ULL << sq;
  if (side == WHITE)
  {
    // White pawn attackers are on sq-7 (east) and sq-9 (west); mask wraparound
    uint64_t east = (bb >> 7) & ~FILE_H;
    uint64_t west = (bb >> 9) & ~FILE_A;
    return west | east;
  }
  else
  {
    // Black pawn attackers are on sq+7 (west) and sq+9 (east); mask wraparound
    uint64_t west = (bb << 7) & ~FILE_A;
    uint64_t east = (bb << 9) & ~FILE_H;
    return west | east;
  }
}

// Static Exchange Evaluation (swap-off). Returns net material if the
// capture sequence on the target square is played out with optimal play.
int static_exchange_eval(const Board &board, const Move &m)
{
  if (!m.isCapture())
    return 0;

  const Side us = static_cast<Side>(board.side);
  const Side them = (us == WHITE ? BLACK : WHITE);

  const int fromSq64 = m.from();
  const int toSq64 = m.to();
  const bool isEP = (m.flags() & MF_EN_PASSANT_CAPTURE) != 0;
  const int captureSq64 = isEP ? (us == WHITE ? toSq64 - 8 : toSq64 + 8) : toSq64;
  const int targetSq64 = toSq64;

  const int fromSq88 = SQ64_to_0x88(fromSq64);
  const int capSq88 = SQ64_to_0x88(captureSq64);

  const int movingPiece = board.squares[fromSq88];
  if (movingPiece == EMPTY)
    return 0;

  const PieceType movingType = m.isPromotion() ? m.promotion() : static_cast<PieceType>(type_of(movingPiece));
  const int victimPiece = isEP ? (us == WHITE ? BPAWN : WPAWN) : board.squares[capSq88];
  const PieceType victimType = static_cast<PieceType>(type_of(victimPiece));

  if (victimType == EMPTY)
    return 0;

  uint64_t occ = board.bb_occ;
  uint64_t bb[16];
  for (int i = 0; i < 16; ++i) bb[i] = board.bb_piece[i];

  auto clear_bit = [](uint64_t &b, int sq64) { b &= ~(1ULL << sq64); };
  auto set_bit = [](uint64_t &b, int sq64) { b |= (1ULL << sq64); };

  // Remove moving piece from origin
  clear_bit(bb[movingPiece], fromSq64);
  occ &= ~(1ULL << fromSq64);

  // Remove captured pawn in EP, or victim on target square
  if (isEP)
  {
    clear_bit(bb[victimPiece], captureSq64);
    occ &= ~(1ULL << captureSq64);
  }
  else
  {
    if (victimPiece != EMPTY)
    {
      clear_bit(bb[victimPiece], captureSq64);
      occ &= ~(1ULL << captureSq64);
    }
  }

  // Place moving piece on target
  const int movingOnTarget = (static_cast<int>(us) << 3) | static_cast<int>(movingType);
  set_bit(bb[movingOnTarget], targetSq64);
  occ |= (1ULL << targetSq64);

  int gains[32];
  gains[0] = heuristic_piece_value(victimType);
  int depth = 0;

  Side side = them; // opponent to recapture
  int targetPiece = movingOnTarget;

  auto attackers_of_side = [&](Side s, uint64_t occBB, uint64_t pieces[]) -> uint64_t {
    uint64_t pawns = pieces[(static_cast<int>(s) << 3) | PAWN];
    uint64_t knights = pieces[(static_cast<int>(s) << 3) | KNIGHT];
    uint64_t bishops = pieces[(static_cast<int>(s) << 3) | BISHOP];
    uint64_t rooks = pieces[(static_cast<int>(s) << 3) | ROOK];
    uint64_t queens = pieces[(static_cast<int>(s) << 3) | QUEEN];
    uint64_t kings = pieces[(static_cast<int>(s) << 3) | KING];

    uint64_t bbTarget = 1ULL << targetSq64;
    uint64_t raw = 0ULL;
    raw |= pawn_attackers_to(targetSq64, s) & pawns;
    raw |= knightAttacks[targetSq64] & knights;
    uint64_t bishopRay = bishopAttacks(targetSq64, occBB);
    raw |= bishopRay & (bishops | queens);
    uint64_t rookRay = rookAttacks(targetSq64, occBB);
    raw |= rookRay & (rooks | queens);
    raw |= kingAttacks[targetSq64] & kings;
    raw &= ~bbTarget; // exclude piece currently on target

    // Filter out pinned attackers (removing fromSq while keeping target occupied must not expose own king).
    if (kings == 0) return raw; // no king info; skip filter
    int kingSq = __builtin_ctzll(kings);
    uint64_t oppBish = pieces[((static_cast<int>(s) ^ 1) << 3) | BISHOP] | pieces[((static_cast<int>(s) ^ 1) << 3) | QUEEN];
    uint64_t oppRook = pieces[((static_cast<int>(s) ^ 1) << 3) | ROOK] | pieces[((static_cast<int>(s) ^ 1) << 3) | QUEEN];

    uint64_t filtered = 0ULL;
    uint64_t tmp = raw;
    while (tmp)
    {
      uint64_t lsb = tmp & -tmp;
      int fromSq = __builtin_ctzll(lsb);
      tmp ^= lsb;

      uint64_t occTest = occBB & ~(1ULL << fromSq); // remove attacker; target stays occupied
      bool kingDiag = (bishopAttacks(kingSq, occTest) & oppBish) != 0ULL;
      bool kingOrth = (rookAttacks(kingSq, occTest) & oppRook) != 0ULL;
      if (!(kingDiag || kingOrth))
      {
        filtered |= lsb;
      }
    }
    return filtered;
  };

  while (true)
  {
    uint64_t attackers = attackers_of_side(side, occ, bb);
    if (!attackers)
      break;

    // Select least valuable attacker of this side
    int fromSq = -1;
    int attackerPiece = -1;
    auto pick_attacker = [&](PieceType pt, uint64_t mask) -> bool {
      if (mask == 0) return false;
      fromSq = __builtin_ctzll(mask);
      attackerPiece = (static_cast<int>(side) << 3) | static_cast<int>(pt);
      return true;
    };

    uint64_t mask;
    // Pawns
    mask = attackers & bb[(static_cast<int>(side) << 3) | PAWN];
    if (pick_attacker(PAWN, mask)) goto found_attacker;
    // Knights
    mask = attackers & bb[(static_cast<int>(side) << 3) | KNIGHT];
    if (pick_attacker(KNIGHT, mask)) goto found_attacker;
    // Bishops
    mask = attackers & bb[(static_cast<int>(side) << 3) | BISHOP];
    if (pick_attacker(BISHOP, mask)) goto found_attacker;
    // Rooks
    mask = attackers & bb[(static_cast<int>(side) << 3) | ROOK];
    if (pick_attacker(ROOK, mask)) goto found_attacker;
    // Queens
    mask = attackers & bb[(static_cast<int>(side) << 3) | QUEEN];
    if (pick_attacker(QUEEN, mask)) goto found_attacker;
    // Kings
    mask = attackers & bb[(static_cast<int>(side) << 3) | KING];
    if (pick_attacker(KING, mask)) goto found_attacker;

  found_attacker:
    if (attackerPiece == -1)
      break;

    depth += 1;
    if (depth >= static_cast<int>(sizeof(gains) / sizeof(gains[0])))
      break; // safety guard

    gains[depth] = heuristic_piece_value(static_cast<PieceType>(type_of(targetPiece))) - gains[depth - 1];

    // Capture: remove current target piece, move attacker onto target
    clear_bit(bb[targetPiece], targetSq64);
    clear_bit(bb[attackerPiece], fromSq);
    occ &= ~(1ULL << targetSq64);
    occ &= ~(1ULL << fromSq);
    targetPiece = attackerPiece;
    set_bit(bb[targetPiece], targetSq64);
    occ |= (1ULL << targetSq64);

    side = (side == WHITE ? BLACK : WHITE);
  }

  // Propagate best achievable scores backward
  while (--depth >= 0)
  {
    gains[depth] = std::max(-gains[depth + 1], gains[depth]);
  }

  return gains[0];
}

// Estimate whether a quiet move provokes a favorable forced recapture for the opponent.
// Returns penalty in centipawns to be applied to ordering/eval heuristics.
static int compute_provoke_penalty(Board &board, const Move &quietMove, Side us)
{
  // Only apply to quiet moves
  if (quietMove.isCapture()) return 0;

  if (!make_move(board, quietMove))
    return 0;

  const Side opp = (us == WHITE ? BLACK : WHITE);
  MoveList oppMoves;
  get_variant_moves(board, opp, oppMoves); // variant enforces capture-only if any capture exists

  int penalty = 0;
  if (!oppMoves.empty() && oppMoves.moves[0].isCapture())
  {
    int worst = 0;
    for (int i = 0; i < oppMoves.count; ++i)
    {
      const Move &m = oppMoves.moves[i];
      if (!m.isCapture()) continue;

      // Placeholder SEE: captured value - attacker value
      int capturedVal = heuristic_piece_value(m.captured());
      int attackerPiece = board.squares[SQ64_to_0x88(m.from())];
      int attackerVal = heuristic_piece_value(type_of(attackerPiece));
      int gain = capturedVal - attackerVal;
      if (gain > worst) worst = gain;
    }

    if (worst >= 0)
    {
      penalty = PROVOKE_PENALTY_CP;
    }
  }

  unmake_move(board);
  return penalty;
}

int search(Board &board,
           int depth,
           int alpha,
           int beta,
           int ply,
           EvalFn evalFn,
           int captureChainLen,
           int extensionsUsed,
           bool isNullSearch)
{
  if (g_time_budget && time_check_due()) {
    bool hard_stop = time_expired();
    if (hard_stop) {
      // On hard timeout, preserve bounds by returning current alpha.
      return SCORE_TIME_ABORT;
    }
    if (g_time_soft_abort) {
      // Soft timeout flagged: request graceful unwind.
      return SCORE_TIME_ABORT;
    }
  }
// #ifdef ENGINE_LOGGING
//   log_msg("search start depth=" + std::to_string(depth) +
//           " alpha=" + std::to_string(alpha) +
//           " beta=" + std::to_string(beta) +
//           " ply=" + std::to_string(ply));
// #endif
  const int alphaOrig = alpha;
  const uint64_t key = board.zobrist_key;
  const Side sideToMove = static_cast<Side>(board.side);
  const bool inCheck = isInCheck(board, sideToMove);

  int ttScore = 0;
  Move ttMove;
  if (TT.probe(key, depth, alpha, beta, ply, ttScore, ttMove))
  {
    // Maintain PV on TT hit
    pvLength[ply] = 0;
    if (!ttMove.isNull())
    {
      pvTable[ply][0] = ttMove;
      pvLength[ply] = 1;
    }
    return ttScore;
  }

  // Generate moves after TT miss so hits avoid move gen cost.
  MoveList moves;
  get_variant_moves(board, sideToMove, moves);

  // Precompute provoke penalties for quiet moves at the root (cheap heuristic).
  std::unordered_map<uint32_t, int> quietPenalties;
  if (ply == 0)
  {
    for (int i = 0; i < moves.count; ++i)
    {
      const Move &m = moves.moves[i];
      if (m.isCapture()) continue;
      int pen = compute_provoke_penalty(board, m, sideToMove);
      if (pen > 0)
      {
        quietPenalties[m.raw()] = pen;
      }
    }
  }

  auto quietPenalty = [&](const Move &m) -> int {
    if (ply != 0) return 0;
    auto it = quietPenalties.find(m.raw());
    return (it == quietPenalties.end() ? 0 : it->second);
  };

  // Capture-chain extension: once per path, trigger after consecutive captures
  // when the position still forces captures (variant move list is capture-only).
  const bool forcedCaptures = (moves.count > 0) && moves.moves[0].isCapture();
  int effectiveDepth = depth;
  int usedExtensions = extensionsUsed;
  if (captureChainLen >= CAPTURE_CHAIN_EXTENSION_TRIGGER &&
      forcedCaptures &&
      usedExtensions < CAPTURE_CHAIN_EXTENSION_MAX)
  {
    effectiveDepth += 1;
    usedExtensions += 1;
  }

  // Optional probe at the extended depth to reuse deeper TT entries
  if (effectiveDepth != depth &&
      TT.probe(key, effectiveDepth, alpha, beta, ply, ttScore, ttMove))
  {
    pvLength[ply] = 0;
    if (!ttMove.isNull())
    {
      pvTable[ply][0] = ttMove;
      pvLength[ply] = 1;
    }
    return ttScore;
  }

  // Initialize PV length for this ply (no moves yet)
  pvLength[ply] = 0;

  if (moves.empty())
  {
    if (inCheck)
    {
      // Checkmate: side to move has no moves and is in check.
      // Encode mate as a large negative score, slightly adjusted by ply
      // so closer mates are better (for the winning side).
      int mateScore = -SCORE_MATE + ply;
      TT.store(key, effectiveDepth, mateScore, TTFlag::EXACT, Move(), ply);
      return mateScore;
    }
    else
    {
      // Stalemate: draw
      TT.store(key, effectiveDepth, 0, TTFlag::EXACT, Move(), ply);
      return 0;
    }
  }

  // --- Depth / leaf handling ---
  // 50-move rule or insufficient material → draw
  if (board.halfmove_clock >= 100 || isInsufficientMaterial(board))
  {
    TT.store(key, effectiveDepth, 0, TTFlag::EXACT, Move(), ply);
    return 0;
  }

  if (effectiveDepth <= 0)
  {
    return qsearch(board, alpha, beta, ply, evalFn);
  }

  // --- Null-move pruning ---
  // Skip in check, after a null search, with active EP, or in thin/zugzwang material.
  auto is_potential_zugzwang = [&](const Board &bIn) {
    int totalPawns  = popcount(bb_of(bIn, WPAWN)) + popcount(bb_of(bIn, BPAWN));
    int totalQueens = popcount(bb_of(bIn, WQUEEN)) + popcount(bb_of(bIn, BQUEEN));
    int totalRooks  = popcount(bb_of(bIn, WROOK))  + popcount(bb_of(bIn, BROOK));
    int totalMinors = popcount(bb_of(bIn, WKNIGHT)) + popcount(bb_of(bIn, WBISHOP)) +
                      popcount(bb_of(bIn, BKNIGHT)) + popcount(bb_of(bIn, BBISHOP));
    return (totalPawns == 0 && totalQueens == 0 && totalRooks == 0 && totalMinors <= 2);
  };

  const bool hasActiveEP = (board.ep_square != NO_SQUARE);
  const bool nearFiftyMove = (board.halfmove_clock >= 98);

  // Static eval computed once per node (lazy) for futility and reuse.
  int staticEval = 0;
  bool haveStaticEval = false;

  if (!isNullSearch &&
      !inCheck &&
      ply > 0 &&
      !hasActiveEP &&
      !nearFiftyMove &&
      has_enough_material_for_null(board, sideToMove) &&
      !is_potential_zugzwang(board))
  {
    // Avoid null move when in mate-bound windows; preserve mate distance ordering.
    if (beta < SCORE_MATE - 2 * MAX_PLY && beta > -SCORE_MATE + 2 * MAX_PLY)
    {
      const int nullReduction = is_clear_endgame_for_null(board) ? 3 : 2;
      // Require enough remaining depth after reduction to keep cutoff stable.
      if (effectiveDepth >= nullReduction + 2)
      {
      int staticEval = evalFn(board);
      if (staticEval >= beta)
      {
        NullUndo nu;
        if (make_null(board, nu))
        {
          int nullDepth = effectiveDepth - 1 - nullReduction;
            int nullScore = -search(board, nullDepth, -beta, -beta + 1, ply + 1, evalFn, /*captureChainLen=*/0, usedExtensions, /*isNullSearch=*/true);
            if (nullScore == SCORE_TIME_ABORT) {
              unmake_null(board, nu);
              return SCORE_TIME_ABORT;
            }
            unmake_null(board, nu);

          if (nullScore >= beta)
          {
            // Store safe lower bound and return beta to avoid polluting TT with reduced-depth score.
            TT.store(key, nullDepth, beta, TTFlag::LOWERBOUND, Move(), ply);
            return beta;
          }
        }
      }
    }
    }
  }

  int bestScore = -SCORE_INF;
  Move bestMove; // for PV / TT (not used directly by caller)
  bool didCutoff = false;
  const bool isPVNode = (beta > alpha + 1);
  const bool inCheckParent = isInCheck(board, sideToMove);

  // Hash move ordering: search TT move first if present.
  auto captureScore = [&](const Move &m) -> int {
    int victimVal = 0;
    if (m.flags() & MF_EN_PASSANT_CAPTURE)
    {
      int to88 = SQ64_to_0x88(m.to());
      int epSq = (sideToMove == WHITE) ? (to88 - 16) : (to88 + 16); // captured pawn is one rank behind target
      if (!(epSq & 0x88))
      {
        int victimPiece = board.squares[epSq];
        victimVal = heuristic_piece_value(type_of(victimPiece));
      }
    }
    else
    {
      victimVal = heuristic_piece_value(m.captured());
    }

    int attackerVal = 0;
    if (m.isPromotion() && m.isCapture())
    {
      attackerVal = heuristic_piece_value(m.promotion());
    }
    else
    {
      int from88 = SQ64_to_0x88(m.from());
      if (!(from88 & 0x88))
      {
        int attackerPiece = board.squares[from88];
        if (attackerPiece != EMPTY && color_of(attackerPiece) == sideToMove)
        {
          attackerVal = heuristic_piece_value(type_of(attackerPiece));
        }
      }
    }

    return victimVal * 10 - attackerVal; // MVV-LVA scaled to integers
  };

  int sortStart = 0;
  if (!ttMove.isNull())
  {
    for (int i = 0; i < moves.count; ++i)
    {
      if (moves.moves[i].raw() == ttMove.raw())
      {
        std::swap(moves.moves[0], moves.moves[i]);
        sortStart = 1; // keep TT move fixed at front
        break;
      }
    }
  }
  struct OrderKey
  {
    bool isCapture = false;
    int capScore = 0;
    int attackerVal = 0;
    int seeScore = 0;
    int killerRank = -1; // 0/1 for killer slots, -1 otherwise
    int historyScore = 0;
    int quietPenaltyVal = 0;
  };
  std::vector<OrderKey> keys(moves.count);
  for (int i = 0; i < moves.count; ++i)
  {
    const Move &m = moves.moves[i];
    OrderKey k{};
    k.isCapture = m.isCapture();
    if (k.isCapture)
    {
      k.capScore = captureScore(m);
      k.seeScore = static_exchange_eval(board, m);
      if (m.isPromotion())
      {
        k.attackerVal = heuristic_piece_value(m.promotion());
      }
      else
      {
        int from88 = SQ64_to_0x88(m.from());
        if (!(from88 & 0x88))
        {
          int attackerPiece = board.squares[from88];
          if (attackerPiece != EMPTY && color_of(attackerPiece) == sideToMove)
          {
            k.attackerVal = heuristic_piece_value(type_of(attackerPiece));
          }
        }
      }
    }
    else
    {
      k.quietPenaltyVal = quietPenalty(m);
      // Killer flag: only for quiet moves
      int killerRank = -1;
      if (killerMoves[ply][0].raw() == m.raw()) killerRank = 0;
      else if (killerMoves[ply][1].raw() == m.raw()) killerRank = 1;
      k.killerRank = killerRank;
      int sideIdx = static_cast<int>(sideToMove);
      int from = m.from();
      int to = m.to();
      if (from >= 0 && from < 64 && to >= 0 && to < 64)
      {
        k.historyScore = historyTable[sideIdx][from][to];
      }
    }
    keys[i] = k;
  }

  // Sort by precomputed keys using stable indices to avoid address-based lookups
  std::vector<int> order(moves.count);
  for (int i = 0; i < moves.count; ++i) order[i] = i;

  std::stable_sort(order.begin() + sortStart, order.begin() + moves.count, [&](int ia, int ib) {
    const OrderKey &ka = keys[ia];
    const OrderKey &kb = keys[ib];

    if (ka.isCapture != kb.isCapture) return ka.isCapture; // captures before quiets

    if (ka.isCapture)
    {
      if ((ka.seeScore >= 0) != (kb.seeScore >= 0)) return ka.seeScore >= 0; // prefer non-losing captures
      if (ka.seeScore != kb.seeScore) return ka.seeScore > kb.seeScore;
      if (ka.capScore != kb.capScore) return ka.capScore > kb.capScore; // higher MVV-LVA first
      if (ka.attackerVal != kb.attackerVal) return ka.attackerVal < kb.attackerVal; // lighter attacker wins tie
      return false;
    }

    // Quiet move ordering: killers first
    if (ka.killerRank != kb.killerRank)
    {
      // Valid killer ranks (0,1) outrank non-killers (-1); lower rank wins ties
      if (ka.killerRank == -1) return false;
      if (kb.killerRank == -1) return true;
      return ka.killerRank < kb.killerRank;
    }

    // Then history heuristic
    if (ka.historyScore != kb.historyScore) return ka.historyScore > kb.historyScore;

    if (ka.quietPenaltyVal != kb.quietPenaltyVal) return ka.quietPenaltyVal < kb.quietPenaltyVal;
    return false; // keep stable order otherwise
  });

  std::vector<Move> reordered(moves.count);
  for (int i = 0; i < moves.count; ++i) reordered[i] = moves.moves[order[i]];
  for (int i = 0; i < moves.count; ++i) moves.moves[i] = reordered[i];

  // Compute static eval once per node (lazy)
  auto get_static_eval = [&]() -> int {
    if (!haveStaticEval)
    {
      staticEval = evalFn(board); // pre-move eval
      haveStaticEval = true;
    }
    return staticEval;
  };

  for (int i = 0; i < moves.count; ++i)
  {
    Move m = moves.moves[i];

    // Negamax: flip perspective and bounds
    int nextChainLen = m.isCapture() ? (captureChainLen + 1) : 0;
    int searchDepthChild = effectiveDepth - 1;
    int score = 0;

    // Futility pruning for shallow depths on quiet moves (no captures/promos), not in check, not capture-only.
    if (!inCheck &&
        nextChainLen == 0 &&
        searchDepthChild <= 2 &&
        !m.isCapture() &&
        !m.isPromotion())
    {
      // Avoid futility in clear endgames/zugzwang-prone cases or narrow windows.
      if (!is_clear_endgame_for_null(board) && (beta - alpha) > 1)
      {
        // Skip futility if the quiet move is tactically losing.
        if (static_exchange_eval(board, m) >= 0)
        {
          int evalVal = get_static_eval();
          // Avoid futility if we are near mate bounds.
          if (evalVal < SCORE_MATE - MAX_PLY && evalVal > -SCORE_MATE + MAX_PLY)
          {
            if (searchDepthChild == 1 && evalVal + 100 < alpha)
            {
              continue;
            }
            if (searchDepthChild == 2 && evalVal + 200 < alpha)
            {
              continue;
            }
          }
        }
      }
    }

    if (!make_move(board, m))
      continue; // illegal move; skip

    const Side nextSide = static_cast<Side>(board.side);
    const Side oppSide = (nextSide == WHITE ? BLACK : WHITE);
    const bool givesCheck = isInCheck(board, oppSide);

    int reduction = 0;
    if (!isPVNode &&
        !inCheckParent &&
        moves.count > 1 &&
        nextChainLen == 0 &&     // do not reduce after capture sequences
        searchDepthChild >= 2 && // parent depth >=3
        i >= 3 &&                // 4th move or later (0-based)
        i < (moves.count - 1) && // avoid reducing a possibly forced last move
        !m.isCapture() &&
        !m.isPromotion() &&
        !givesCheck)
    {
      reduction = 1;
      if (i >= 6) reduction += 1;
      if (effectiveDepth > 6) reduction += 1;
      int reducedDepth = searchDepthChild - reduction;
      if (reducedDepth < 1) reducedDepth = 1;

      score = -search(board, reducedDepth, -beta, -alpha, ply + 1, evalFn, nextChainLen, usedExtensions, /*isNullSearch=*/false);
      if (score == SCORE_TIME_ABORT) {
        unmake_move(board);
        return SCORE_TIME_ABORT;
      }
      if (score > alpha)
      {
        if (score >= beta)
        {
          // Reduced search already fails high; treat as cutoff.
        }
        else
        {
          // Re-search at full depth when reduced search improves alpha.
          score = -search(board, searchDepthChild, -beta, -alpha, ply + 1, evalFn, nextChainLen, usedExtensions, /*isNullSearch=*/false);
          if (score == SCORE_TIME_ABORT) {
            unmake_move(board);
            return SCORE_TIME_ABORT;
          }
        }
      }
    }
    else
    {
      score = -search(board, searchDepthChild, -beta, -alpha, ply + 1, evalFn, nextChainLen, usedExtensions, /*isNullSearch=*/false);
      if (score == SCORE_TIME_ABORT) {
        unmake_move(board);
        return SCORE_TIME_ABORT;
      }
    }

    unmake_move(board);

    int penalty = 0;
    if (!m.isCapture() && !m.isPromotion())
    {
      penalty = quietPenalty(m);
    }
    int scoreCmp = (ply == 0 ? score - penalty : score);

    if (scoreCmp > bestScore)
    {
      bestScore = scoreCmp;
      bestMove = m;

      // --- PV update: this move becomes first move of new PV at this ply ---
      pvTable[ply][0] = m;
      pvLength[ply] = pvLength[ply + 1] + 1;

      for (int j = 0; j < pvLength[ply + 1]; ++j)
      {
        pvTable[ply][j + 1] = pvTable[ply + 1][j];
      }
    }

    if (bestScore > alpha)
    {
      alpha = bestScore;
      if (m.isQuiet() && !m.isCapture())
      {
        // Quiet move improved alpha: small history bump
        update_history(m, sideToMove, 10);
      }
      // TODO (PV-node info for TT, if desired)
    }

    // Alpha-beta cutoff
    if (alpha >= beta)
    {
      // Store quiet killers for this ply
      store_killer(ply, m);
      // Strong bonus for causing cutoff
      update_history(m, sideToMove, 50);

      // Store cutoff as LOWERBOUND with the move that caused it.
      bestMove = m;
      TT.store(key, effectiveDepth, alpha, TTFlag::LOWERBOUND, bestMove, ply);
      didCutoff = true;
      break;
    }
  }

  // Store result in TT with appropriate flag if no earlier cutoff store.
  if (!didCutoff)
  {
    TTFlag storeFlag = TTFlag::EXACT;
    if (bestScore <= alphaOrig)
    {
      storeFlag = TTFlag::UPPERBOUND;
    }
    TT.store(key, effectiveDepth, bestScore, storeFlag, bestMove, ply);
  }

  return bestScore;
}

static inline bool time_check_due() {
  // Throttle to every 1024 nodes
  return (++g_time_check_counter & 1023ULL) == 0;
}

static inline bool time_expired() {
  if (g_time_abort) return true;
  if (!g_time_budget) return false;
  auto now = std::chrono::steady_clock::now();
  auto elapsed_ms = std::chrono::duration_cast<std::chrono::milliseconds>(now - g_search_start).count();
  const long long soft_base = std::max(0, g_time_budget->soft_ms);
  long long hard_base = std::max(0, g_time_budget->hard_ms);
  const long long soft_limit = soft_base + std::max(0, g_soft_overrun_ms);
  if (hard_base < soft_limit) {
    hard_base = soft_limit;
  }
  const long long hard_limit = hard_base;
  if (elapsed_ms >= hard_limit) {
    g_time_abort = true;    // hard stop: abort immediately
    return true;
  }
  if (elapsed_ms >= soft_limit) {
    g_time_soft_abort = true;  // soft stop: request graceful exit
    return false;
  }
  return false;
}

Move getBestMove(Board &board, int maxDepth, EvalFn evalFn, const TimeBudget *timeBudget, int *outRootScore)
{
#ifdef ENGINE_LOGGING
  log_msg("getBestMove start maxDepth=" + std::to_string(maxDepth));
#endif
  clear_killers();
  Move bestMove;     // move to return
  int bestScore = 0; // last stable root score
  bool havePV = false;
  int prevDepthScore = 0;
  bool havePrevDepthScore = false;
  Move lastCompletedPVMove;
  int lastCompletedPVScore = 0;

  // Iterative deepening loop: depths 1..maxDepth
  g_time_budget = timeBudget;
  g_search_start = std::chrono::steady_clock::now();
  g_time_abort = false;
  g_time_soft_abort = false;
  g_time_check_counter = 0;
  g_soft_overrun_ms = 0;

  for (int depth = 1; depth <= maxDepth; ++depth)
  {
    int alpha, beta;
    int score;

    if (depth == 1)
    {
      // First iteration: full-window search.
      alpha = -SCORE_INF;
      beta = SCORE_INF;
      score = search(board, depth, alpha, beta, /*ply=*/0, evalFn, /*captureChainLen=*/0, /*extensionsUsed=*/0, /*isNullSearch=*/false);
    }
    else
    {
      alpha = bestScore - ASP_WINDOW;
      beta = bestScore + ASP_WINDOW;

      // First try with the narrow window
      score = search(board, depth, alpha, beta, /*ply=*/0, evalFn, /*captureChainLen=*/0, /*extensionsUsed=*/0, /*isNullSearch=*/false);
      if (score == SCORE_TIME_ABORT) {
        g_time_abort = true;
      }

      // If we fail low or high, re-search with full window
      if (!g_time_abort && (score <= alpha || score >= beta))
      {
        alpha = -SCORE_INF;
        beta = SCORE_INF;
      score = search(board, depth, alpha, beta, /*ply=*/0, evalFn, /*captureChainLen=*/0, /*extensionsUsed=*/0, /*isNullSearch=*/false);
        if (score == SCORE_TIME_ABORT) {
          g_time_abort = true;
        }
      }
    }

    // Abort if time expired during this iteration
    if (g_time_abort || time_expired()) {
      break;
    }

    // After search, PV for this depth is in pvTable[0]
    if (pvLength[0] > 0)
    {
      if (havePrevDepthScore && std::abs(score - prevDepthScore) > 40) {
        g_soft_overrun_ms = 25; // allow small overrun on unstable PV
      } else {
        g_soft_overrun_ms = 0;
      }
      prevDepthScore = score;
      havePrevDepthScore = true;

      bestMove = pvTable[0][0];
      bestScore = score;
      havePV = true;
      lastCompletedPVMove = bestMove;
      lastCompletedPVScore = bestScore;

      // (Optional) You can print or log the PV line here for debugging:
      // std::cout << "info depth " << depth << " score cp " << bestScore << " pv ";
      // for (int i = 0; i < pvLength[0]; ++i) {
      //   std::cout << pvTable[0][i].toString() << ' ';
      // }
      // std::cout << std::endl;
    }
    else
    {
      // No PV at this depth: no legal moves (mate/stalemate).
      // We can break early, as deeper searches won't change that.
      break;
    }

    // Decay history each completed iteration to keep recency bias
    decay_history();

    if (g_time_abort || g_time_soft_abort) {
      break;
    }
  }

  if (outRootScore) {
    *outRootScore = bestScore;
  }

  if (!havePV && !lastCompletedPVMove.isNull()) {
    bestMove = lastCompletedPVMove;
    bestScore = lastCompletedPVScore;
    havePV = true;
  }

  if (!havePV)
  {
    // No legal moves from the start position.
    return Move(); // null move; caller can interpret as game over.
  }

  return bestMove;
}
