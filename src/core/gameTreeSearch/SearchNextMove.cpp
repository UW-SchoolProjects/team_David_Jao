// Simple material draw detector (insufficient material).
bool isInsufficientMaterial(const Board &b)
{
  // If any pawn, rook, or queen exists, it's not insufficient.
  auto any = [&](int piece) { return bb_of(b, piece) != 0ULL; };
  if (any(WPAWN) || any(BPAWN) || any(WROOK) || any(BROOK) || any(WQUEEN) || any(BQUEEN))
    return false;

  bool whiteMinor = bb_of(b, WKNIGHT) || bb_of(b, WBISHOP);
  bool blackMinor = bb_of(b, BKNIGHT) || bb_of(b, BBISHOP);
  int whiteMinorCount = popcount(bb_of(b, WKNIGHT)) + popcount(bb_of(b, WBISHOP));
  int blackMinorCount = popcount(bb_of(b, BKNIGHT)) + popcount(bb_of(b, BBISHOP));

  // Only kings
  if (!whiteMinor && !blackMinor)
    return true;

  // King + single minor vs king
  if ((whiteMinorCount == 1 && blackMinorCount == 0) || (whiteMinorCount == 0 && blackMinorCount == 1))
    return true;

  // King + bishop vs king + bishop with bishops on same color squares.
  if (whiteMinorCount == 1 && blackMinorCount == 1 &&
      bb_of(b, WBISHOP) && bb_of(b, BBISHOP))
  {
    // Bishops on same color? Use square color of lsb.
    auto lsb = [](uint64_t bb) { return __builtin_ctzll(bb); };
    int wSq = lsb(bb_of(b, WBISHOP));
    int bSq = lsb(bb_of(b, BBISHOP));
    bool wDark = ((wSq & 1) ^ ((wSq >> 3) & 1)) != 0;
    bool bDark = ((bSq & 1) ^ ((bSq >> 3) & 1)) != 0;
    if (wDark == bDark)
      return true;
  }

  return false;
}

// PV table: pvTable[ply][i] is the i-th move in the PV at search ply `ply`.
static Move pvTable[MAX_PLY][MAX_PLY];

// PV length per ply
static int pvLength[MAX_PLY];

// Killer moves: killerMoves[ply][0/1] hold quiet moves causing recent cutoffs.
static Move killerMoves[MAX_PLY][2];

// History heuristic: history[side][from][to] accumulates quiet move success.
static int historyTable[2][64][64];

static inline void clear_killers()
{
  for (int d = 0; d < MAX_PLY; ++d)
  {
    killerMoves[d][0] = Move();
    killerMoves[d][1] = Move();
  }
}

static inline void clear_history()
{
  for (int s = 0; s < 2; ++s)
    for (int f = 0; f < 64; ++f)
      for (int t = 0; t < 64; ++t)
        historyTable[s][f][t] = 0;
}

static inline void store_killer(int ply, const Move &m)
{
  if (!m.isQuiet()) return; // killers only track quiet refutations
  uint32_t raw = m.raw();
  if (killerMoves[ply][0].raw() == raw)
  {
    return; // already best killer
  }
  if (killerMoves[ply][1].raw() == raw)
  {
    // Promote second killer to first
    killerMoves[ply][1] = killerMoves[ply][0];
    killerMoves[ply][0] = m;
    return;
  }
  killerMoves[ply][1] = killerMoves[ply][0];
  killerMoves[ply][0] = m;
}

static inline void update_history(const Move &m, Side side, int bonus)
{
  if (!m.isQuiet()) return;
  int from = m.from();
  int to = m.to();
  if (from < 0 || from >= 64 || to < 0 || to >= 64) return;
  int &entry = historyTable[side][from][to];
  // Clamp to avoid overflow
  const int maxVal = 1 << 20;
  entry += bonus;
  if (entry > maxVal) entry = maxVal;
  if (entry < -maxVal) entry = -maxVal;
}

static inline void decay_history()
{
  for (int s = 0; s < 2; ++s)
    for (int f = 0; f < 64; ++f)
      for (int t = 0; t < 64; ++t)
        historyTable[s][f][t] >>= 1;
}

