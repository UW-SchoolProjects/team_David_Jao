#ifndef QUIESCENCE_H
#define QUIESCENCE_H

#include "../nextMoveGeneration/move.h"
#include "../board/board.h"
#include "eval.h"
#include "SearchConfig.h"

/**
 * Quiescence search entry point.
 *
 * Intent:
 *   - Stabilize leaf evaluations by exploring forcing moves (captures, and
 *     checking moves when in check) to avoid horizon effects.
 *   - Stand-pat = static eval (side-to-move perspective).
 *   - Alpha/beta pruning semantics match the main negamax search.
 *
 * Conventions:
 *   - Returns score from the current side-to-move perspective.
 *   - Uses `evalFn` for stand-pat and leaf static eval; the callback signature
 *     matches the rest of the engine (`int eval(const Board&)`).
 *   - Respects MAX_PLY to prevent runaway recursion.
 *
 * Move generation policy:
 *   - If the side to move is in check, generate full legal moves (evasion
 *     requires quiet king moves).
 *   - Otherwise, generate captures only if any exist (reuse capture-only
 *     variant filter); if no captures, stand-pat is the terminal value.
 *
 * Parameters:
 *   board  - mutable board; make/unmake is performed internally.
 *   alpha  - lower bound (negamax window).
 *   beta   - upper bound.
 *   ply    - current ply from root (for MAX_PLY guard and mate scoring).
 *   evalFn - static evaluation callback; must not mutate the board.
 *
 * Return:
 *   The best score within [alpha, beta] from the perspective of the side to
 *   move at `board`.
 */
int qsearch(Board &board, int alpha, int beta, int ply, EvalFn evalFn);

#endif // QUIESCENCE_H
