void init_engine_session(EngineSession &sess) {
    clear_board(sess.board);
    setup_startpos(sess.board);
    rebuild_bitboards(sess.board);
    TT.clear();
    log_msg("Session initialized");
    log_board_fen(sess.board, "Startpos");

    sess.side_to_move = WHITE;
    sess.board.side   = WHITE;
    sess.engine_side  = WHITE;

    sess.mode             = EngineMode::FORCE;
    sess.quit_requested   = false;
    sess.my_time_ms       = 0;
    sess.opp_time_ms      = 0;
    sess.moves_per_session = 0;
    sess.base_time_ms      = 0;
    sess.increment_ms      = 0;
    sess.time_per_move_ms  = 0;
    sess.max_depth         = 0;
    sess.last_my_move_ts   = std::chrono::steady_clock::now();
    sess.last_opp_move_ts  = std::chrono::steady_clock::now();
    sess.last_ping_id      = 0;
}

