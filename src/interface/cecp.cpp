std::string move_to_uci(const Move &m) {
    // Your Move::from()/to() are 0..63 indices.
    int from64 = m.from();
    int to64   = m.to();

    char ff, rf, ft, rt;
    sq64_to_file_rank(from64, ff, rf);
    sq64_to_file_rank(to64,   ft, rt);

    std::string s;
    s.reserve(5);
    s.push_back(ff);
    s.push_back(rf);
    s.push_back(ft);
    s.push_back(rt);

    if (m.isPromotion()) {
        PieceType pt = m.promotion();
        char promoChar = 'q';
        switch (pt) {
        case KNIGHT: promoChar = 'n'; break;
        case BISHOP: promoChar = 'b'; break;
        case ROOK:   promoChar = 'r'; break;
        case QUEEN:  promoChar = 'q'; break;
        default:     promoChar = 'q'; break;
        }
        s.push_back(promoChar);
    }
    return s;
}

// Generate all legal moves under your forced-capture rule
static void generate_variant_moves(Board &b, MoveList &out) {
    out.clear();
    // Wrapper enforces "must capture if a capture exists".
    get_variant_moves(b, static_cast<Side>(b.side), out);
}

bool parse_uci_move(Board &b,
                    const std::string &text,
                    Move &out_move)
{
    MoveList moves;
    generate_variant_moves(b, moves);

    for (int i = 0; i < moves.count; ++i) {
        const Move &m = moves.moves[i];
        if (move_to_uci(m) == text) {
            out_move = m;
            return true;
        }
    }
    return false; // illegal or unknown
}

static Move search_best_move(EngineSession &sess) {
    // Use the engine's negamax search with quiescence and basic eval.
    // Depth can be tuned; 'sd' overrides the default when provided.
    int searchDepth = sess.max_depth > 0 ? sess.max_depth : 8;
    log_msg("search_best_move: starting search depth " + std::to_string(searchDepth));
    Move best = getBestMove(sess.board, searchDepth, basicEvaluate);
    log_msg("search_best_move: search finished");
    return best;
}

