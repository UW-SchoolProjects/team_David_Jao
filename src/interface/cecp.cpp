static void do_engine_move(EngineSession &sess) {
    log_msg("do_engine_move entry");
    auto move_start_ts = std::chrono::steady_clock::now();

    Move best = search_best_move(sess);

    if (best.isNull()) {
        log_msg("No legal move to play (null move).");
        // No legal moves: mate or stalemate; GUI will send 'result'.
    return;
  }

  std::string s = move_to_uci(best);

  // Your make_move from MoveApply.h updates:
  // - squares
  // - side to move
  // - castling, ep, clocks
  // - zobrist
  bool ok = make_move(sess.board, best);
  if (!ok) {
    // This should never happen if moves came from validMoveGeneration.
    log_msg("make_move failed for engine move " + s);
    return;
  }

  sess.side_to_move = sess.board.side;
  log_msg("Engine plays " + s);
  log_board_fen(sess.board, "After engine move");

  auto move_end_ts = std::chrono::steady_clock::now();
  auto elapsed_ms_ll = std::chrono::duration_cast<std::chrono::milliseconds>(move_end_ts - move_start_ts).count();
  apply_my_move_elapsed(sess, static_cast<int>(elapsed_ms_ll), move_end_ts);

  // Use std::endl to force an immediate flush to the GUI.
  std::cout << "move " << s << std::endl;
}

static void handle_go(EngineSession &sess) {
    sess.mode = EngineMode::PLAYING;
    // "go" resumes play with the current engine side; move immediately if it's our turn.
    if (sess.board.side == sess.engine_side) {
        do_engine_move(sess);
    }
}

static void handle_usermove(EngineSession &sess, const std::string &mvStr) {
    log_msg("usermove " + mvStr);
    Move m;
    if (!parse_uci_move(sess.board, mvStr, m)) {
        log_msg("usermove rejected: not found in legal list");
        std::cout << "Illegal move: " << mvStr << "\n";
        return;
    }
    log_msg("parsed uci move " + std::to_string(m.from()) + std::to_string(m.to()));
    bool ok = make_move(sess.board, m);
    if (!ok) {
        log_msg("usermove rejected: make_move failed");
        std::cout << "Illegal move: " << mvStr << "\n";
        return;
    }

    sess.side_to_move = sess.board.side;
    log_board_fen(sess.board, "After usermove");
    // Opponent just moved; record their move end (our clock starts now).
    sess.last_opp_move_ts = std::chrono::steady_clock::now();

    log_msg(sess.mode == EngineMode::PLAYING ? "play is on" : "play not on");
    if (sess.mode == EngineMode::PLAYING && sess.board.side == sess.engine_side) {
        do_engine_move(sess);
    }
}

