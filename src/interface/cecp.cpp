static void handle_result(EngineSession &sess, const std::string&) {
    // Game ended; engine goes back to force mode and reset timing state.
    sess.mode = EngineMode::FORCE;
    sess.my_time_ms = 0;
    sess.opp_time_ms = 0;
    sess.moves_per_session = 0;
    sess.base_time_ms = 0;
    sess.increment_ms = 0;
    sess.time_per_move_ms = 0;
    sess.max_depth = 0;
    sess.has_root_score = false;
    sess.last_root_score = 0;
    auto now = std::chrono::steady_clock::now();
    sess.last_my_move_ts = now;
    sess.last_opp_move_ts = now;
}

static void handle_quit(EngineSession &sess) {
    sess.quit_requested = true;
}

static void handle_setboard(EngineSession &sess, const std::string &fen) {
    if (!load_fen(sess.board, fen)) {
        std::cout << "Illegal position: " << fen << "\n";
        return;
    }

    TT.clear();
    sess.side_to_move = sess.board.side;
    sess.mode = EngineMode::FORCE;
    sess.my_time_ms       = 0;
    sess.opp_time_ms      = 0;
    sess.moves_per_session = 0;
    sess.base_time_ms      = 0;
    sess.increment_ms      = 0;
    sess.time_per_move_ms  = 0;
    sess.max_depth         = 0;
    sess.has_root_score    = false;
    sess.last_root_score   = 0;
    auto now = std::chrono::steady_clock::now();
    sess.last_my_move_ts   = now;
    sess.last_opp_move_ts  = now;
}

// ---------------------------
// Main CECP loop
// ---------------------------

void cecp_main_loop(EngineSession &sess) {
    std::string line;

    while (!sess.quit_requested && std::getline(std::cin, line)) {
        log_msg("raw line: " + line);
        // Strip possible \r from Windows line endings
        if (!line.empty() && line.back() == '\r') {
            line.pop_back();
        }
        if (line.empty()) continue;

        std::istringstream iss(line);
        std::string cmd;
        iss >> cmd;

        log_msg(std::string("cmd: ") + cmd + " | line: " + line);

        if (cmd == "xboard") {
            handle_xboard(sess);
        }
        else if (cmd == "protover") {
            int v = 1; iss >> v;
            handle_protover(sess, v);
        }
        else if (cmd == "new") {
            handle_new(sess);
        }
        else if (cmd == "force") {
            handle_force(sess);
        }
        else if (cmd == "white") {
            handle_white(sess);
        }
        else if (cmd == "black") {
            handle_black(sess);
        }
        else if (cmd == "go") {
            handle_go(sess);
        }
        else if (cmd == "usermove") {
            std::string mvStr; iss >> mvStr;
            handle_usermove(sess, mvStr);
        }
        else if (cmd == "time") {
            int t; iss >> t;
            handle_time(sess, t);
        }
        else if (cmd == "otim") {
            int t; iss >> t;
            handle_otim(sess, t);
        }
        else if (cmd == "level") {
            int moves = 0;
            std::string baseTimeToken;
            int increment = 0;
            iss >> moves >> baseTimeToken;
            if (!(iss >> increment)) {
                increment = 0;
            }
            if (!baseTimeToken.empty()) {
                handle_level(sess, moves, baseTimeToken, increment);
            }
        }
        else if (cmd == "st") {
            int seconds = 0; iss >> seconds;
            handle_st(sess, seconds);
        }
        else if (cmd == "sd") {
            int depth = 0; iss >> depth;
            handle_sd(sess, depth);
        }
        else if (cmd == "ping") {
            int id; iss >> id;
            handle_ping(sess, id);
        }
        else if (cmd == "result") {
            handle_result(sess, line);
        }
        else if (cmd == "setboard") {
            std::string fenRest;
            std::getline(iss, fenRest);
            if (!fenRest.empty() && fenRest.front() == ' ') {
                fenRest.erase(0, fenRest.find_first_not_of(' '));
            }
            handle_setboard(sess, fenRest);
        }
        else if (cmd == "quit") {
            handle_quit(sess);
        }
        else {
            // Unknown or unsupported command: safe to ignore.
        }

        std::fflush(stdout);
        log_msg("ready to take command again");
    }
    log_msg("I should not be seen");
}
