static void do_engine_move(EngineSession &sess);

static void handle_xboard(EngineSession&) {
    // nothing special needed
}

static void handle_protover(EngineSession&, int version) {
    (void)version;

    // Minimal feature set to keep XBoard / cutechess happy.
    std::cout
        << "feature myname=\"" << kEngineName << "\" variants=\"normal\" "
        << "setboard=1 usermove=1 ping=1 done=1\n";
}

static void handle_new(EngineSession &sess) {
    init_engine_session(sess);
}

static void handle_force(EngineSession &sess) {
    sess.mode = EngineMode::FORCE;
}

static void handle_white(EngineSession &sess) {
    sess.engine_side = WHITE;
    sess.mode = EngineMode::PLAYING;
    if (sess.board.side == WHITE) {
        do_engine_move(sess);
    }
}

static void handle_black(EngineSession &sess) {
    sess.engine_side = BLACK;
    sess.mode = EngineMode::PLAYING;
    if (sess.board.side == BLACK) {
        do_engine_move(sess);
    }
}

static void do_engine_move(EngineSession &sess) {
    log_msg("do_engine_move entry");
    auto move_start_ts = std::chrono::steady_clock::now();
    sess.last_my_move_ts = move_start_ts;

    Move best = search_best_move(sess);

    if (best.isNull()) {
        log_msg("No legal move to play (null move).");
        // No legal moves: mate or stalemate; GUI will send 'result'.
    return;
  }

  std::string s = move_to_uci(best);

  // Your make_move from MoveApply.h updates:
  // - squares
  // - side to move
  // - castling, ep, clocks
  // - zobrist
  bool ok = make_move(sess.board, best);
  if (!ok) {
    // This should never happen if moves came from validMoveGeneration.
    log_msg("make_move failed for engine move " + s);
    return;
  }

  sess.side_to_move = sess.board.side;
  log_msg("Engine plays " + s);
  log_board_fen(sess.board, "After engine move");

  auto move_end_ts = std::chrono::steady_clock::now();
  auto elapsed_ms_ll = std::chrono::duration_cast<std::chrono::milliseconds>(move_end_ts - move_start_ts).count();
  int elapsed_ms = clamp_non_negative(elapsed_ms_ll);
  if (sess.my_time_ms > 0) {
      sess.my_time_ms = std::max(0, sess.my_time_ms - elapsed_ms);
  }
  if (sess.increment_ms > 0) {
      sess.my_time_ms += sess.increment_ms;
  }
  sess.last_my_move_ts = move_end_ts;
  sess.last_opp_move_ts = move_end_ts; // opponent clock starts now

  // Use std::endl to force an immediate flush to the GUI.
  std::cout << "move " << s << std::endl;
}

static void handle_go(EngineSession &sess) {
    sess.mode = EngineMode::PLAYING;
    // "go" resumes play with the current engine side; move immediately if it's our turn.
    if (sess.board.side == sess.engine_side) {
        do_engine_move(sess);
    }
}

static void handle_usermove(EngineSession &sess, const std::string &mvStr) {
    log_msg("usermove " + mvStr);
    auto now = std::chrono::steady_clock::now();
    if (sess.opp_time_ms > 0) {
        auto opp_elapsed_ms_ll = std::chrono::duration_cast<std::chrono::milliseconds>(now - sess.last_opp_move_ts).count();
        int opp_elapsed_ms = clamp_non_negative(opp_elapsed_ms_ll);
        sess.opp_time_ms = std::max(0, sess.opp_time_ms - opp_elapsed_ms);
    }
    sess.last_opp_move_ts = now;
    Move m;
    if (!parse_uci_move(sess.board, mvStr, m)) {
        log_msg("usermove rejected: not found in legal list");
        std::cout << "Illegal move: " << mvStr << "\n";
        return;
    }
    log_msg("parsed uci move " + std::to_string(m.from()) + std::to_string(m.to()));
    bool ok = make_move(sess.board, m);
    if (!ok) {
        log_msg("usermove rejected: make_move failed");
        std::cout << "Illegal move: " << mvStr << "\n";
        return;
    }

    sess.side_to_move = sess.board.side;
    log_board_fen(sess.board, "After usermove");
    sess.last_my_move_ts = std::chrono::steady_clock::now(); // our clock starts

    log_msg(sess.mode == EngineMode::PLAYING ? "play is on" : "play not on");
    if (sess.mode == EngineMode::PLAYING && sess.board.side == sess.engine_side) {
        do_engine_move(sess);
    }
}

static void handle_time(EngineSession &sess, int cs) {
    sess.my_time_ms = cs_to_ms(cs);
    sess.last_my_move_ts = std::chrono::steady_clock::now();
}

static void handle_otim(EngineSession &sess, int cs) {
    sess.opp_time_ms = cs_to_ms(cs);
    sess.last_opp_move_ts = std::chrono::steady_clock::now();
}

static void handle_ping(EngineSession &sess, int id) {
    sess.last_ping_id = id;
    std::cout << "pong " << id << "\n";
}

static void handle_level(EngineSession &sess,
                         int moves_per_session,
                         const std::string &base_time_token,
                         int increment_seconds)
{
    sess.moves_per_session = moves_per_session;
    sess.base_time_ms      = parse_time_token_ms(base_time_token);
    sess.increment_ms      = increment_seconds * 1000;
}

static void handle_st(EngineSession &sess, int seconds) {
    sess.time_per_move_ms = seconds * 1000;
}

static void handle_sd(EngineSession &sess, int depth) {
    sess.max_depth = depth;
}

static void handle_result(EngineSession &sess, const std::string&) {
    // Game ended; engine goes back to force mode.
    sess.mode = EngineMode::FORCE;
}

static void handle_quit(EngineSession &sess) {
    sess.quit_requested = true;
}

static void handle_setboard(EngineSession &sess, const std::string &fen) {
    if (!load_fen(sess.board, fen)) {
        std::cout << "Illegal position: " << fen << "\n";
        return;
    }

    TT.clear();
    sess.side_to_move = sess.board.side;
    sess.mode = EngineMode::FORCE;
    sess.my_time_ms       = 0;
    sess.opp_time_ms      = 0;
    sess.moves_per_session = 0;
    sess.base_time_ms      = 0;
    sess.increment_ms      = 0;
    sess.time_per_move_ms  = 0;
    sess.max_depth         = 0;
    auto now = std::chrono::steady_clock::now();
    sess.last_my_move_ts   = now;
    sess.last_opp_move_ts  = now;
}

// ---------------------------
// Main CECP loop
// ---------------------------

void cecp_main_loop(EngineSession &sess) {
    std::string line;

    while (!sess.quit_requested && std::getline(std::cin, line)) {
        log_msg("raw line: " + line);
        // Strip possible \r from Windows line endings
        if (!line.empty() && line.back() == '\r') {
            line.pop_back();
        }
        if (line.empty()) continue;

        std::istringstream iss(line);
        std::string cmd;
        iss >> cmd;

        log_msg(std::string("cmd: ") + cmd + " | line: " + line);

        if (cmd == "xboard") {
            handle_xboard(sess);
        }
        else if (cmd == "protover") {
            int v = 1; iss >> v;
            handle_protover(sess, v);
        }
        else if (cmd == "new") {
            handle_new(sess);
        }
        else if (cmd == "force") {
            handle_force(sess);
        }
        else if (cmd == "white") {
            handle_white(sess);
        }
        else if (cmd == "black") {
            handle_black(sess);
        }
        else if (cmd == "go") {
            handle_go(sess);
        }
        else if (cmd == "usermove") {
            std::string mvStr; iss >> mvStr;
            handle_usermove(sess, mvStr);
        }
        else if (cmd == "time") {
            int t; iss >> t;
            handle_time(sess, t);
        }
        else if (cmd == "otim") {
            int t; iss >> t;
            handle_otim(sess, t);
        }
        else if (cmd == "level") {
            int moves = 0;
            std::string baseTimeToken;
            int increment = 0;
            iss >> moves >> baseTimeToken;
            if (!(iss >> increment)) {
                increment = 0;
            }
            if (!baseTimeToken.empty()) {
                handle_level(sess, moves, baseTimeToken, increment);
            }
        }
        else if (cmd == "st") {
            int seconds = 0; iss >> seconds;
            handle_st(sess, seconds);
        }
        else if (cmd == "sd") {
            int depth = 0; iss >> depth;
            handle_sd(sess, depth);
        }
        else if (cmd == "ping") {
            int id; iss >> id;
            handle_ping(sess, id);
        }
        else if (cmd == "result") {
            handle_result(sess, line);
        }
        else if (cmd == "setboard") {
            std::string fenRest;
            std::getline(iss, fenRest);
            if (!fenRest.empty() && fenRest.front() == ' ') {
                fenRest.erase(0, fenRest.find_first_not_of(' '));
            }
            handle_setboard(sess, fenRest);
        }
        else if (cmd == "quit") {
            handle_quit(sess);
        }
        else {
            // Unknown or unsupported command: safe to ignore.
        }

        std::fflush(stdout);
        log_msg("ready to take command again");
    }
    log_msg("I should not be seen");
}
