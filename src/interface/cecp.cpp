std::string move_to_uci(const Move &m) {
    // Your Move::from()/to() are 0..63 indices.
    int from64 = m.from();
    int to64   = m.to();

    char ff, rf, ft, rt;
    sq64_to_file_rank(from64, ff, rf);
    sq64_to_file_rank(to64,   ft, rt);

    std::string s;
    s.reserve(5);
    s.push_back(ff);
    s.push_back(rf);
    s.push_back(ft);
    s.push_back(rt);

    if (m.isPromotion()) {
        PieceType pt = m.promotion();
        char promoChar = 'q';
        switch (pt) {
        case KNIGHT: promoChar = 'n'; break;
        case BISHOP: promoChar = 'b'; break;
        case ROOK:   promoChar = 'r'; break;
        case QUEEN:  promoChar = 'q'; break;
        default:     promoChar = 'q'; break;
        }
        s.push_back(promoChar);
    }
    return s;
}

// Generate all legal moves under your forced-capture rule
static void generate_variant_moves(Board &b, MoveList &out) {
    out.clear();
    // Wrapper enforces "must capture if a capture exists".
    get_variant_moves(b, static_cast<Side>(b.side), out);
}

bool parse_uci_move(Board &b,
                    const std::string &text,
                    Move &out_move)
{
    MoveList moves;
    generate_variant_moves(b, moves);

    for (int i = 0; i < moves.count; ++i) {
        const Move &m = moves.moves[i];
        if (move_to_uci(m) == text) {
            out_move = m;
            return true;
        }
    }
    return false; // illegal or unknown
}

static Move search_best_move(EngineSession &sess) {
    auto move_start = std::chrono::steady_clock::now();
    // Use the engine's negamax search with quiescence and basic eval.
    // Depth can be tuned; 'sd' overrides the default when provided.
    int searchDepth = sess.max_depth > 0 ? sess.max_depth : 8;
    log_msg("search_best_move: starting search depth " + std::to_string(searchDepth));
    bool in_check = false;
    bool capture_heavy = false;
    gather_root_context(sess.board, in_check, capture_heavy);

    int remaining = sess.my_time_ms > 0 ? sess.my_time_ms : 50;
    int moves_left = sess.moves_per_session > 0 ? sess.moves_per_session : 30;
    TimeBudget budget = compute_time_budget(remaining,
                                            sess.increment_ms,
                                            sess.time_per_move_ms,
                                            moves_left,
                                            in_check,
                                            capture_heavy);

    int rootScore = 0;
    Move best = getBestMove(sess.board, searchDepth, basicEvaluate, &budget, &rootScore);
    sess.last_root_score = rootScore;
    sess.has_root_score = true;
#ifdef ENGINE_LOGGING
    auto move_end = std::chrono::steady_clock::now();
    auto raw_ms = std::chrono::duration_cast<std::chrono::milliseconds>(move_end - move_start).count();
    long long move_elapsed_ms = raw_ms < 0 ? 0LL : raw_ms;
    int logged_score = (rootScore == SCORE_TIME_ABORT && sess.has_root_score) ? sess.last_root_score : rootScore;
    log_msg("METRIC move_time ms=" + std::to_string(move_elapsed_ms) +
            " depth=" + std::to_string(searchDepth) +
            " score=" + std::to_string(logged_score));
#endif
    log_msg("search_best_move: search finished");
    return best;
}

